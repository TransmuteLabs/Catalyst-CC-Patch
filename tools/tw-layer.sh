# shellcheck shell=bash
# ЕДИНСТВЕННЫЙ дом разбора вывода tweakcc. Подключается (`source`) и конвейером,
# и свипом: вторая реализация уже расходилась с первой (свип считал галочки
# своим awk, без фильтра знаков и без части ступеней LC_ALL=C), и два читателя
# одного вывода давали двум потребителям разные множества.
#
# ФАЙЛ ТОЛЬКО ОБЪЯВЛЯЕТ. Ни `set`, ни вывода, ни единого действия на верхнем
# уровне: подключающий приносит своё состояние оболочки, и подключение не имеет
# права его менять.
#
# Перечисление секций приходит АРГУМЕНТОМ, а не читается отсюда: константы
# принадлежат конвейеру (claude-patch-all.sh), свип берёт их из снимка кита, и
# третья копия здесь разошлась бы с обеими.
#
# Разделитель перечисления -- ТАБУЛЯЦИЯ. `split()` в awk принимает третий
# аргумент как РЕГЕКСП: одиночная вертикальная черта разбирается буквально лишь
# по свойству реализации, а не по гарантии текста. Табуляция метасимволом
# регекспа не является нигде.
#
# LC_ALL=C на каждой ступени: знаки не-ASCII, и разбор под локалью машины
# считает мимо (измерено на этом ките).

# Полный набор знаков, которые печатает форк: ✓ легло, ✗ не легло, ○ не
# пробовалось по конфигу дома, ⊘ не пробовалось по версии, ≡ пробовалось и не
# изменило ничего. Набор -- ДАННЫЕ, а не перечисление внутри регекспа: строка
# правки опознаётся по ФОРМЕ (четыре пробела, ОДИН знак, пробел), поэтому знак,
# которого здесь нет, всё равно ВИДЕН часовому и может быть отвергнут --
# теперь и знак ИЗ ASCII. Регексп, перечислявший знаки, шестого знака не видел
# вовсе -- форк, заведший его, растворялся бы в тишине вместо отказа.
#
# Ни один байт набора не лежит в ASCII (все знаки трёхбайтные, байты ≥ 0x80):
# потому `index(marks, mark)` на односимвольном знаке ИЗ ASCII не может дать
# случайного совпадения с байтом внутри знака набора.
TW_MARKS='✓✗○⊘≡'

# Строка правки: четыре пробела, знак, пробел, имя. Знак -- РОВНО ОДИН символ:
# ведущий байт и его продолжения UTF-8 (0x80-0xBF). Разбор идёт под LC_ALL=C,
# где символ -- байт, поэтому «ровно один символ» записывается байтами, а не
# как `[^ ]`: `[^ ]` под C-локалью съедает ОДИН байт и трёхбайтный знак форка
# (✓ = E2 9C 93) под форму не подпадает вовсе -- измерено, все счёта дают ноль.
#
# Прежняя форма требовала байта вне ASCII, и знак ИЗ ASCII не видел никто:
# строка `    - Thinking block styling` выпадала из всех счётов молча, а первой
# говорила дверь уровня, обвиняя реестр форка вместо формы вывода.
#
# «Ровно один символ», а не «любой не-пробел»: под четырьмя пробелами бывает и
# посторонний текст, но его первое слово длиннее одного символа (второй байт --
# не продолжение UTF-8), и под форму он не подпадает.
__TW_LINE_RE='^    [^ ][\200-\277]* '

# ЯКОРЬ БЛОКА РЕЗУЛЬТАТОВ -- граница предмета всех читателей ниже.
#
# Форк печатает ДВА блока правок под ОДНИМИ И ТЕМИ ЖЕ заголовками секций:
# предапплайный список ПЛАНА (`src/applyPlan.ts:269`, строка
# «    • Имя (id)[ [default-on]]») и блок РЕЗУЛЬТАТОВ (`src/index.tsx:124`).
# Формой они неразличимы -- четыре пробела, не-ASCII значок, пробел, имя, -- и
# заголовки секций у них общие (замерено на прогоне 2.1.261: «Always Applied»,
# «Misc Configurable», «Features» встречаются по обе стороны якоря).
#
# Поэтому предмет ограничивается ОБЛАСТЬЮ, а не перечислением исключений: всё
# до якоря слою не принадлежит ПО ПОСТРОЕНИЮ. Перечисление исключений пришлось
# бы дополнять на каждую новую строку плана, и часовой знаков, ради которого
# перечисление и заводилось, снова краснил бы на здоровом прогоне.
TW_RESULTS_ANCHOR='Patches applied (run with --show-unchanged to show all patches):'

# <файл вывода> -> сколько раз встретился якорь блока результатов.
#
# Читается ПОТРЕБИТЕЛЕМ и обязано быть равно 1: ноль якорей и два якоря -- две
# разные поломки, и обе тихие. При нуле область пуста, все счёта дают ноль, и
# дверь уровня обвиняет реестр форка вместо формы вывода. При двух в один счёт
# попадают две сборки. Дверь отказа живёт у потребителя (там, где живут все
# прочие отказы кита), а измерение -- здесь, рядом с самим якорем.
#
# Сравнение ПРЕФИКСОМ (`index($0, anchor) == 1`), а не регекспом: в якоре есть
# круглые скобки и дефисы, экранирование их под регексп -- лишняя поверхность
# отказа на строке, которую форк печатает буквально.
tw_results_anchor_count() {
  LC_ALL=C awk -v anchor="$TW_RESULTS_ANCHOR" '
    index($0, anchor) == 1 { n++ }
    END { print n + 0 }
  ' "$1" 2>/dev/null || echo 0
}

# <файл вывода> <перечисление секций через TAB> <класс знаков> -> ИМЕНА по строке
tw_layer_names() {
  LC_ALL=C awk -v secs="$2" -v marks="$3" -v linere="$__TW_LINE_RE" \
               -v anchor="$TW_RESULTS_ANCHOR" '
    BEGIN { n = split(secs, s, "\t"); for (i = 1; i <= n; i++) want[s[i]] = 1 }
    # Область: от якоря до конца входа. `cur` сбрасывается НА якоре -- иначе
    # заголовок секции из блока плана дожил бы до первой строки результатов и
    # приписал её чужой секции.
    index($0, anchor) == 1 { inres = 1; cur = ""; next }
    !inres { next }
    # Заголовок секции -- ровно два пробела и двоеточие в конце. Заголовки
    # повторяются при КАЖДОМ вызове tweakcc: секция переустанавливается,
    # состояние между вызовами не копится.
    /^  [^ ].*:$/ { cur = $0; sub(/^  /, "", cur); sub(/:$/, "", cur); next }
    $0 ~ linere {
      mark = $0; sub(/^    /, "", mark); sub(/ .*$/, "", mark)
      if (index(marks, mark) == 0) next
      if (!(cur in want)) next
      # Имя -- до тире с описанием: описание принадлежит tweakcc и меняется от
      # версии к версии, привязка к нему пинила бы чужой текст. Отрезка через
      # sub, а не substr: длина знака в байтах и в символах разная, и разбор
      # обязан давать одно имя при любой локали прибора.
      name = $0; sub(/^    [^ ]* /, "", name)
      sub(/ — .*$/, "", name); sub(/[[:space:]]+$/, "", name)
      if (name != "") print name
    }
  ' "$1" 2>/dev/null || true
}

# Часовой ФОРМЫ. В блоке результатов КАЖДАЯ строка формы правки обязана
# принадлежать ровно одному счёту, а счёт -- это пара «известная секция +
# известный знак». Всё, что этой паре не отвечает, из счётов выпадает молча:
#   -- строка до первого заголовка либо под незнакомой секцией: слоя у неё нет,
#      и молчаливое отнесение к любому вернуло бы отказ по чужой причине, ради
#      снятия которого слои и различаются секцией;
#   -- строка под известной секцией с НЕЗНАКОМЫМ знаком: её не считает ни один
#      класс, то есть попытка исчезает из всех счётов разом. Прежний часовой
#      перечислял знаки регекспом и такой строки не видел вовсе.
#
# Правило больше не перечисляет исключений: буллеты плана форка вышли из
# предмета вместе с ограничением области (см. TW_RESULTS_ANCHOR), а не особой
# оговоркой. Правило с оговоркой уже краснило на здоровом прогоне 2.1.261 --
# заголовки секций у плана и у результатов ОДНИ И ТЕ ЖЕ, и «незнакомый знак под
# известной секцией» ловил ровно план.
# <файл вывода> <перечисление ВСЕХ секций через TAB> -> строки-нарушители
tw_unsectioned_lines() {
  LC_ALL=C awk -v secs="$2" -v marks="$TW_MARKS" -v linere="$__TW_LINE_RE" \
               -v anchor="$TW_RESULTS_ANCHOR" '
    BEGIN { n = split(secs, s, "\t"); for (i = 1; i <= n; i++) want[s[i]] = 1 }
    index($0, anchor) == 1 { inres = 1; cur = ""; next }
    !inres { next }
    /^  [^ ].*:$/ { cur = $0; sub(/^  /, "", cur); sub(/:$/, "", cur); next }
    $0 ~ linere {
      mark = $0; sub(/^    /, "", mark); sub(/ .*$/, "", mark)
      if ((cur in want) && index(marks, mark) > 0) next
      print
    }
  ' "$1" 2>/dev/null || true
}

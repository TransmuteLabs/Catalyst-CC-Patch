# ЕДИНСТВЕННЫЙ дом имени файла корпуса.
#
# Имя строили независимо свип и наполнитель, и одно направление расхождения
# МОЛЧИТ: сменив суффикс только у наполнителя, получаешь новые закачки под
# новым именем при живых старых файлах -- свип продолжает мерить старые байты,
# их пины сходятся, и прогон зелёный. Поэтому имя выводит одна функция, и
# стенд отдельно требует, чтобы литерала суффикса не было больше нигде.
corpus_file_name() { printf '%s.pristine' "$1"; }

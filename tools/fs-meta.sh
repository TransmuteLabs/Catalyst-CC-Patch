# shellcheck shell=bash
# ЕДИНСТВЕННЫЙ дом чтения метаданных файла: метка времени и инод. Подключается
# (`source`) тремя РАЗНЫМИ точками входа -- конвейером (claude-patch-all.sh),
# свипом (tools/sweep.sh) и зондом пути сборки (tools/build-path-probe.sh).
# Копий идиомы было три, и они уже разошлись: две несли отравляющую форму,
# третья -- безопасную, и различие держалось на ОДНОМ пробеле.
#
# ФАЙЛ ТОЛЬКО ОБЪЯВЛЯЕТ. Ни `set`, ни вывода, ни единого действия на верхнем
# уровне, кроме снятия имени платформы: подключающий приносит своё состояние
# оболочки (конвейер идёт под `set -euo pipefail`), и подключение не имеет
# права его менять.
#
# КОНСТРЕЙНТ, ради которого дом заведён: форма «попробуй BSD, иначе GNU»
# (`stat -f %m "$f" || stat -c %Y "$f"`) здесь ЗАПРЕЩЕНА НАВСЕГДА. Она не
# деградирует безопасно -- она ОТРАВЛЯЕТ вывод:
#   * у BSD stat ключ `-f` берёт ФОРМАТ следующим словом;
#   * у GNU coreutils `-f` -- это `--file-system`, аргумента он не берёт,
#     поэтому `%m` становится ФАЙЛОВЫМ операндом. GNU stat падает на нём
#     (rc=1), НО ПЕРЕД ПАДЕНИЕМ ПЕЧАТАЕТ В STDOUT статистику файловой системы
#     по второму операнду -- и вывод запасной ветки ДОПИСЫВАЕТСЯ к этой каше.
# Разделитель между честным отказом и отравлением -- ОДИН ПРОБЕЛ после `-f`:
# форма `-f%i` без пробела даёт недопустимую опцию, пустой stdout и честный
# переход на запаску, форма `-f %m` -- четыре строки мусора и цифру за ними.
#
# Замер одной и той же функции на двух машинах (волна 40a):
#   LINUX  (GNU coreutils):  m=[  File: "kitd"
#                                 ID: 97f00000000 Namelen: 255  Type: xfs
#                                 Block size: 4096 ...
#                                 1788824969]                        rc=1
#   macOS  (BSD stat):       m=[1788824971]                          rc=0
# На маке ошибка невидима по устройству: там отравляющая форма ПРАВИЛЬНА.
#
# Поэтому диалект выбирается ПО ПЛАТФОРМЕ и ОДИН РАЗ, а не по коду возврата
# отравляющей команды. Код возврата вообще не участвует в решении: он у
# отравляющей формы равен единице ПРИ УЖЕ НАПЕЧАТАННОМ мусоре, то есть говорит
# о неудаче ПОЗЖЕ, чем мусор попал потребителю.
__FS_META_UNAME="$(uname -s 2>/dev/null || echo unknown)"

# <формат BSD> <формат GNU> <путь> -> ОДНА строка из цифр на stdout, код 0;
# при любом другом ответе -- пустой stdout и код 1.
#
# Вердикт выносит ФОРМА ОТВЕТА, а не код возврата stat. Так и должно быть:
# отравляющая форма отдаёт код 1 вместе с мусором в stdout, а неизвестный
# диалект отдаёт код 1 с пустым stdout -- для потребителя оба случая одинаковы
# («метки нет»), и оба обязаны прийти к нему одним честным отказом, а не
# строкой, которую он примет за число. Проверка -- `case` с классом `[!0-9]`,
# а не `=~`: перевод строки внутри мусора тоже не цифра, поэтому многострочный
# ответ отсекается тем же одним правилом.
__fs_meta_read() {
  local __out
  case "$__FS_META_UNAME" in
    Darwin|*BSD*|DragonFly) __out=$(stat -f "$1" "$3" 2>/dev/null) ;;
    *)                      __out=$(stat -c "$2" "$3" 2>/dev/null) ;;
  esac
  case "$__out" in
    ''|*[!0-9]*) return 1 ;;
  esac
  printf '%s\n' "$__out"
}

# <путь> -> метка времени изменения в секундах эпохи
fs_mtime() { __fs_meta_read '%m' '%Y' "$1"; }

# <путь> -> номер инода
#
# Формат инода у обоих диалектов записывается одинаково (`%i`), и соблазн
# позвать stat одной формой на обе платформы тут максимальный. Он и есть
# ловушка: одинаков ФОРМАТ, а не КЛЮЧ -- `-f` и `-c` остаются разными, и
# перепутанный ключ на Linux вернёт ту же кашу, что и у метки времени.
fs_inode() { __fs_meta_read '%i' '%i' "$1"; }

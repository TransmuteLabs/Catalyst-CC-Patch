#!/usr/bin/env bash
# Наполнение корпуса пристинных образов, на котором работает tools/sweep.sh.
#
# Повод (2026-08-28). Корпус лежал в ~/.local/share/claude/versions как
# <версия>.orig, а фаза «Cleaning up previous versions» самого конвейера удаляет
# оттуда ВСЁ, кроме текущей версии и той, что исполняет живая сессия. Установка
# 2.1.248 честно отработала эту фазу и вместе со старыми сборками унесла образы
# 233/240/243/245/246 -- измерительную базу, на которой меряется каждая волна
# правок. Теперь у корпуса свой каталог, куда очистка не заглядывает.
#
# Коды выхода (подмножество общей таблицы кита -- шапка claude-patch-all.sh):
#   0  корпус наполнен и сходится с пинами
#   1  отказ по существу: реестр не подтвердил байты, файл не прочитать, нет
#      инструмента хеша, список не разбирается
#   2  прибор не может мерить: разбирать нечего -- названного списка нет или
#      сломан контракт вызова разборщика (раунд 19, A-10); либо строки, которой
#      пишется пин, в списке уже нет -- список сменился под прогоном
#   3  замок наполнителя держит другой живой прогон -- повторить позже
#   6  машинерия замка сломана (perl flock не работает) -- повтор не поможет
#
# Источник -- РЕЕСТР npm, а не локальная копия: локальный образ может быть уже
# пропатченным (нашими правками или tweakcc), и корпус из него бесполезен --
# свип мерил бы патч поверх патча.
#
# Качается ПРЯМО в корпус, вызовом download_binary из claude_patch.py, а не
# через `--download-only`. Тот режим кладёт образ в каталог УСТАНОВОК и там же
# заменяет <версия>.orig, а для уже установленной версии оставляет ещё и
# <версия>.staging. Наполнителю корпуса нечего делать в каталоге установок:
# первая редакция этого скрипта подчищала за собой `rm -f $VDIR/$version`, то
# есть отвязала бы образ, который в этот момент исполняет живая сессия.
#
# Идемпотентно для ЗАПИНЕННЫХ версий: лежащий образ с сошедшимся пином не
# перекачивается. Лежащий образ БЕЗ пина -- качается: пин обязан родиться из
# байт реестра, а не из того, что кто-то положил в каталог. Список версий --
# общий со свипом, tools/corpus-versions.txt.
set -u
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
KIT=$(cd "$HERE/.." && pwd)
# Те же ручки, что у свипа, и с той же целью -- стенд (см. комментарий там).
CORPUS="${CORPUS_DIR:-$HOME/.local/share/claude-patch/corpus}"
# Имя файла корпуса -- из общего дома (см. комментарий там).
. "$HERE/corpus-file-name.sh"
LIST="${CORPUS_LIST:-$HERE/corpus-versions.txt}"
[[ -f "$LIST" ]] || { echo "ОТКАЗ: нет списка версий $LIST" >&2; exit 2; }
mkdir -p "$CORPUS"

# Замок наполнителя.
#
# Два наполнителя, стартовавших разом, делят и каталог корпуса, и СПИСОК: у
# каждого свой временный файл закачки, но список оба переписывают целиком, и
# каждый пишет его из СВОЕГО снимка, снятого до закачек. Кто пишет вторым,
# возвращает файлу свою версию строк -- пины, записанные первым, исчезают, а
# оба процесса отчитываются успехом. Замок в дескрипторе (как у конвейера и
# свипа): протухших не бывает, ядро отпускает его вместе с последним
# держателем. Ждать нечего -- отказ немедленный и с именем причины.
#
# Дескриптор 6: у 8 сидит замок свипа, у 9 -- замок конвейера, а наполнитель
# законно зовут из-под них обоих.
# Недокачанный образ убирается на любом выходе: стадия `.part.<pid>` лежит в
# ЖИВОМ корпусе (вне дерева), а трап не исполняется на SIGKILL -- такие обломки
# снимает прополка на старте (ниже) по мёртвому pid (раунд 19, В-11).
# Часовой завершения обязателен для КАЖДОГО EXIT-трапа: bash 3.2 отдаёт код 0,
# когда скрипт с трапом умирает на фатальной ошибке подстановки, и провал
# невидим вызывающему. Гейт форм оболочки это правило и стережёт -- он же
# поймал эту правку, добавившую трап без часового.
# Сигнальные трапы переводят сигнал в КОД (130/143), а не входят в общий гвард:
# точечный TERM от оператора иначе приходился на последнюю УДАВШУЮСЯ команду,
# и часовой объявлял остановку «ошибкой оболочки».
__DONE=0
__PART=''
__fetch_guard() {
  __rc=$?
  [[ -n "$__PART" ]] && rm -f "$__PART"
  if [[ "${__DONE:-0}" != 1 && "$__rc" == 0 ]]; then
    echo "ОТКАЗ: наполнитель оборвался, не дойдя до конца (ошибка оболочки выше)" >&2
    exit 1
  fi
  exit "$__rc"
}
trap '__fetch_guard' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
FETCH_LOCK="${CORPUS_FETCH_LOCK:-$CORPUS/.fetch.lock}"
exec 6>"$FETCH_LOCK" || { echo "ОТКАЗ: не открыть замок $FETCH_LOCK" >&2; exit 6; }
perl -e 'use Fcntl ":flock"; open(my $fh, ">&=6") or exit 2;
         exit(flock($fh, LOCK_EX|LOCK_NB) ? 0 : 1);'
__frc=$?
if (( __frc != 0 )); then
  if (( __frc == 1 )); then
    echo "ОТКАЗ: другой наполнитель уже идёт (замок $FETCH_LOCK)." >&2
    echo "  кто именно: lsof $FETCH_LOCK" >&2
    exit 3
  fi
  # «Занято» и «машинерия замка сломана» -- разные ответы: первый значит
  # «повторить позже», второй -- «чинить окружение». Общий код 1 их склеивал
  # (раунд 18, F-7).
  echo "ОТКАЗ: не взять замок наполнителя -- машинерия сломана (perl rc=$__frc)" >&2
  exit 6
fi

# Прополка обломков закачек на старте, под замком: трап не исполняется на
# SIGKILL, а имя стадии несёт pid -- ничей обломок опознаётся по мёртвому
# номеру. Живой pid не трогаем: рядом может идти второй наполнитель (другой
# корпус -- другой замок, а список один). Нечисловой суффикс (.part.XXXXXX --
# форма, убранная волной 25) -- сирота ПО ПОСТРОЕНИЮ: прополка идёт под
# замком наполнителя, а замок сериализует писателей на весь прогон, живого
# писателя с такой формой имени не бывает. Убирается безусловно, с тем же
# сообщением, что и обломок мёртвого pid (волна 26).
for __part in "$CORPUS"/*.part.*; do
  [[ -e "$__part" ]] || continue
  __ppid="${__part##*.}"
  if [[ "$__ppid" =~ ^[0-9]+$ ]] && kill -0 "$__ppid" 2>/dev/null; then
    continue
  fi
  rm -f "$__part" && echo "наполнитель убрал обломок закачки мёртвого прогона: $__part"
done

# Инструмент хеша выбирается ОДИН раз, на старте.
#
# Прежняя редакция держала отказ «нет ни shasum, ни sha256sum» ВНУТРИ функции,
# которую зовут только как `got=$(sha256_of ...)`. `exit 1` там убивает подшелл,
# а не скрипт: дальше шёл пустой хеш, который не совпадал с пином, и отказ
# случался по другой причине. Дверь, срабатывающая по касательной, перестаёт
# работать на первом же вызове, где результат не сверяют с пином.
if command -v shasum >/dev/null 2>&1; then HASH=(shasum -a 256)
elif command -v sha256sum >/dev/null 2>&1; then HASH=(sha256sum)
else echo "ОТКАЗ: нет ни shasum, ни sha256sum -- пин корпуса не проверить" >&2; exit 1
fi
# Пустой результат хеширования -- НЕ расхождение пина: файл без права чтения
# давал «файл » и объявлялся подменённым. Свип это различает с волны 18, а
# наполнитель говорил о подмене там, где нечего читать -- и искать шли не там.
sha256_of() {
  local out
  out=$("${HASH[@]}" "$1" 2>/dev/null | awk '{print $1}')
  [[ -n "$out" ]] || return 1
  printf '%s' "$out"
}

# Пины записываются ПОСЛЕ обхода, одной перезаписью.
#
# Прежняя редакция писала пин прямо в цикле, а цикл читал ЭТОТ ЖЕ файл через
# `done < "$LIST"`. Запись делает truncate по тому же иноду, дескриптор чтения
# остаётся за концом файла -- и первая же записанная строка обрывала обход:
# остальные версии молча не качались, а код возврата оставался нулевым. Список
# читается в память до цикла, пины копятся и применяются в конце.
record_pins() {   # пары: версия цифры версия цифры ...
  (( $# )) || return 0
  python3 - "$LIST" "$@" <<'PIN_PY'
import os, sys
path, rest = sys.argv[1], sys.argv[2:]
pins = dict(zip(rest[0::2], rest[1::2]))
lines = open(path).read().splitlines()
seen = set()
for i, ln in enumerate(lines):
    parts = ln.split()
    if len(parts) >= 2 and not parts[0].startswith('#') and parts[1] in pins:
        lines[i] = '%s %s %s' % (parts[0], parts[1], pins[parts[1]])
        seen.add(parts[1])
missing = sorted(set(pins) - seen)
if missing:
    # Класс 2, а не отказ по существу: строки, которой пишется пин, в списке
    # уже нет -- список сменился под прогоном, записывать некуда. sys.exit со
    # СТРОКОЙ отдавал здесь 1, то есть звал чинить корпус вместо
    # разбирательства, кто переписал список (свип контроллера, волна 22).
    sys.stderr.write('в списке нет версий: %s\n' % ', '.join(missing))
    sys.exit(2)
# Запись СТАДИЕЙ и переименованием, а не `open(path, 'w')`.
#
# Прямая перезапись обрезает файл и наполняет его заново: прогон, убитый или
# упавший в этом окне, оставляет список ПУСТЫМ или обрезанным на середине
# строки. Список -- единственный дом версий и пинов корпуса, и обрезанный он
# лишает свип и всю измерительную базу пинов молча (разбор потом объявит
# «строка без пина», но восстановить её будет нечем). Файл во временный,
# fsync, затем os.replace -- переименование в пределах каталога атомарно, и
# читатель всегда видит либо старый список целиком, либо новый целиком.
#
# Имя стадии несёт pid, и стадия снимается на ЛЮБОМ выходе. Фиксированное
# `<список>.new` склеивало двух наполнителей: замок наполнителя стоит на
# КОРПУСЕ (`$CORPUS/.fetch.lock`), а список живёт в ките -- два прогона с
# разными корпусами и одним списком брали каждый свой замок и писали в один
# временный файл, после чего один переименовывал ЧУЖУЮ половину поверх списка.
# Убитый прогон к тому же оставлял `.new` навсегда (круг 21, E-5/F-6).
#
# Остаточное: два таких прогона по-прежнему могут ПОТЕРЯТЬ обновление пина
# (оба прочли список до записи). Это не порча и не требует замка: пин --
# выводимый факт, строка без пина заставляет следующий прогон перекачать образ
# из реестра и записать пин заново.
tmp = path + '.new.%d' % os.getpid()
try:
    with open(tmp, 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
        fh.flush()
        os.fsync(fh.fileno())
    os.replace(tmp, path)
except BaseException:
    try:
        os.unlink(tmp)
    except OSError:
        pass
    raise
PIN_PY
}

# Закачка из реестра во ВРЕМЕННЫЙ файл, имя которого уникально для процесса:
# два наполнителя, стартовавших разом, писали в один и тот же `<образ>.part` и
# обрезали друг друга (download_binary открывает цель на "wb").
fetch_to() {   # версия, путь назначения
  KIT="$KIT" DST="$2" VER="$1" python3 - <<'FETCH_PY'
import os, sys
from pathlib import Path
sys.path.insert(0, os.environ['KIT'])
import claude_patch
claude_patch.download_binary(os.environ['VER'], Path(os.environ['DST']))
FETCH_PY
}

# Формат списка разбирает ОДИН дом на оба инструмента (tools/corpus-list.py).
# Свой разбор у каждого читателя разошёлся: строку без третьего поля свип
# отвергал, а наполнитель качал и записывал ей пин; лишнее поле оба глотали;
# дубль версии под двумя метками оба принимали. Отказ разбора -- отказ здесь,
# до первой сетевой закачки.
ENTRIES=$(python3 "$KIT/tools/corpus-list.py" "$LIST") || {
  __lrc=$?
  if (( __lrc == 2 )); then
    echo "ОТКАЗ: разборщик списка НЕ МЕРИЛ (rc=2): причина строкой выше -- разбирать нечего либо сломан сам прибор" >&2
    exit 2
  fi
  echo "ОТКАЗ: список $LIST не проходит разбор (см. причину выше)" >&2; exit 1; }

rc=0
declare -a NEW_PINS=()
while IFS=$'\t' read -r label version pin; do
  [[ -n "${label:-}" ]] || continue
  dst="$CORPUS/$(corpus_file_name "$version")"
  # Имя недокачанного -- ДЕТЕРМИНИРОВАННОЕ по pid, и оно присваивается ДО
  # того, как файл возникнет: окно «файл уже есть, а __PART ещё пуст» закрыто
  # по построению, а не сужено. Обломки мёртвых pid снимает прополка на старте.
  tmp="$dst.part.$$"
  __PART="$tmp"

  if [[ -s "$dst" ]]; then
    if ! got=$(sha256_of "$dst"); then
      rm -f "$tmp"
      echo "ОТКАЗ: $version лежит, но не прочитать $dst" >&2; rc=1; continue
    fi
    if [[ "$pin" != "-" ]]; then
      rm -f "$tmp"
      if [[ "$got" == "$pin" ]]; then
        echo "уже есть: $version ($(wc -c < "$dst" | tr -d ' ') байт, пин сходится)"
      else
        echo "ОТКАЗ: $version на диске не сходится с пином (пин $pin, файл $got)" >&2; rc=1
      fi
      continue
    fi
    # Пин ещё не записан, а файл уже лежит. Записать хеш диска -- значит
    # объявить эталоном то, что никто не проверял: в корпус мог попасть
    # пропатченный образ или обрубок, и дальше «сток против патча поверх патча»
    # уже не отличить. Пин ставится только по байтам РЕЕСТРА, поэтому версия
    # качается и сверяется с тем, что лежит.
    echo "== $version лежит без пина -- качаю из реестра для сверки"
    if ! fetch_to "$version" "$tmp"; then
      rm -f "$tmp"; echo "ОТКАЗ: не скачать $version для сверки" >&2; rc=1; continue
    fi
    if ! fresh=$(sha256_of "$tmp"); then
      rm -f "$tmp"; echo "ОТКАЗ: $version скачан, но не прочитать для сверки" >&2; rc=1; continue
    fi
    rm -f "$tmp"
    if [[ "$fresh" == "$got" ]]; then
      NEW_PINS+=("$version" "$fresh")
      echo "ok $version: файл совпал с реестром, пин будет записан: $fresh"
    else
      echo "ОТКАЗ: $version в корпусе НЕ равен реестру (файл $got, реестр $fresh)." >&2
      echo "       Пин не записан. Удалите $dst и перезапустите." >&2
      rc=1
    fi
    continue
  fi

  echo "== качаю $version"
  if ! fetch_to "$version" "$tmp"; then
    rm -f "$tmp"; echo "ОТКАЗ на $version" >&2; rc=1; continue
  fi
  if ! got=$(sha256_of "$tmp"); then
    rm -f "$tmp"; echo "ОТКАЗ: $version скачан, но не прочитать $tmp" >&2; rc=1; continue
  fi
  if [[ "$pin" != "-" && "$got" != "$pin" ]]; then
    # Реестр отдал не то, что записано. Это не повод молча заменить пин: файл
    # выбрасывается, прогон краснеет, разбирается человек.
    rm -f "$tmp"
    echo "ОТКАЗ: $version из реестра не сходится с пином (пин $pin, скачано $got)" >&2
    rc=1; continue
  fi
  chmod 755 "$tmp"
  mv "$tmp" "$dst" || { rm -f "$tmp"; echo "ОТКАЗ: не перенести $version" >&2; rc=1; continue; }
  if [[ "$pin" == "-" ]]; then
    NEW_PINS+=("$version" "$got")
    echo "ok $version -> $dst ($(wc -c < "$dst" | tr -d ' ') байт), пин будет записан: $got"
  else
    echo "ok $version -> $dst ($(wc -c < "$dst" | tr -d ' ') байт, пин сходится)"
  fi
done <<< "$ENTRIES"

if (( ${#NEW_PINS[@]} )); then
  __prc=0
  record_pins "${NEW_PINS[@]}" || __prc=$?
  if (( __prc == 0 )); then
    echo "пины записаны: $(( ${#NEW_PINS[@]} / 2 ))"
  elif (( __prc == 2 )); then
    echo "ОТКАЗ: пины НЕ записаны -- список сменился под прогоном (rc=2)" >&2
    # Красное сильнее «прибор не мерил»: если версия уже отказала по существу,
    # класс всего прогона остаётся отказом по существу.
    (( rc == 0 )) && rc=2
  else
    echo "ОТКАЗ: не записать пины" >&2; rc=1
  fi
fi

echo "КОРПУС ($CORPUS):"
ls -l "$CORPUS" | sed 's/^/  /'
__DONE=1   # штатный конец: см. часового выше
exit $rc

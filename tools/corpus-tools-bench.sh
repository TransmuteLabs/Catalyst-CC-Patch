# Круг 25, E-1: bash -n считает heredoc ДАННЫМИ, поэтому замена, сломавшая
# ПИТОН внутри <<'ТЕГ', проходила страж круга 24 как аккуратная -- и краснела
# сценарий разбором, а не механизмом, оставляя тот же след (аудитор доказал
# это на мутации с заменой тела sys.exit внутри PIN_PY у fetch-corpus.sh: bash -n
# давал ноль, py_compile вырезанного тела -- SyntaxError). Извлечение -- ОТДЕЛЬНАЯ
# именованная функция, чтобы её могли позвать и зубы, которым нужно доказать,
# что тело heredoc жертвы вообще разбирается.
# Правило открытия -- то же, что у гейта PYCOMPILE конвейера (claude-patch-all.sh):
# часть строки до первого '#' содержит python3 границей слова, между python3
# и открытием нет '|' ';' '&', и строка КОНЧАЕТСЯ открытием <<'ТЕГ'. Хвост после
# тега отсекает упоминания в комментариях и примерах (у них после тега есть
# текст) -- иначе строка-пример проглотила бы хвост файла как «тело», и страж
# краснел бы на здоровом ките. Тело -- до строки, равной ТЕГУ ДОСЛОВНО.
python_heredoc_bodies() {   # файл-жертва, каталог для тел; печатает число тел
  local f="$1" out="$2" line pre rest mid tag n=0
  local OPEN_RE="<<'([A-Za-z_][A-Za-z0-9_]*)'[[:space:]]*\$"
  tag=''
  while IFS= read -r line || [[ -n "$line" ]]; do
    if [[ -n "$tag" ]]; then
      if [[ "$line" == "$tag" ]]; then tag=''; continue; fi
      printf '%s\n' "$line" >> "$out/body.$n.py"
      continue
    fi
    pre=${line%%#*}
    [[ "$pre" == *python3* ]] || continue
    [[ "$pre" =~ (^|[^A-Za-z0-9_])python3([^A-Za-z0-9_]|$) ]] || continue
    rest=${pre#*python3}
    mid=${rest%<<*}
    [[ "$mid" == *[\|\;\&]* ]] && continue
    [[ "$pre" =~ $OPEN_RE ]] || continue
    tag=${BASH_REMATCH[1]}
    n=$((n+1)); : > "$out/body.$n.py"
  done < "$f"
  printf '%s\n' "$n"
}

# Страж разбираемости .sh-жертвы ЦЕЛИКОМ: сам файл -- bash -n, каждое тело
# heredoc, поданное питону, -- py_compile. Провал любого звена -- ненулевой
# возврат; mutate() переводит его в код «прибор не может мерить».
sh_victim_parses() {   # файл-жертва
  local f="$1" dir n i
  bash -n "$f" 2>/dev/null || return 2
  dir=$(mktemp -d "${TMPDIR:-/tmp}/heredoc.XXXXXX") || return 2
  n=$(python_heredoc_bodies "$f" "$dir")
  # BSD seq при пустом диапазоне (seq 1 0) печатает «1 0» ВНИЗ, а не пустоту:
  # без этой проверки страж гонял бы py_compile по несуществующим файлам
  # и краснел на жертвах без питоньих тел (замерено на этой машине).
  if (( n > 0 )); then
    for i in $(seq 1 "$n"); do
      python3 -m py_compile "$dir/body.$i.py" 2>/dev/null || { rm -rf "$dir"; return 2; }
    done
  fi
  rm -rf "$dir"
  return 0
}

mutate() {   # номер
  local n=$1 f pat rep hits before after
  f="$K/${MUT_FILE[$n]}"; pat="${MUT_PAT[$n]}"; rep="${MUT_REP[$n]}"
  [[ -f "$f" ]] || { say "  ПРОВАЛ мутация $n: нет файла $f"; return 1; }
  # Образец обязан встречаться РОВНО раз. Два совпадения -- и правится первое,
  # то есть, возможно, не то место, а мутация всё равно «применилась»: сценарий
  # покраснел бы по теневому совпадению, доказав чужое правило.
  hits=$(PAT="$pat" perl -0ne 'my $n = () = /$ENV{PAT}/g; print $n' "$f")
  if [[ "$hits" != "1" ]]; then
    say "  ПРОВАЛ мутация $n: образец встречается $hits раз в ${MUT_FILE[$n]}"
    return 1
  fi
  before=$(cat "$f")
  PAT="$pat" REP="$rep" perl -0pi -e 's/$ENV{PAT}/$ENV{REP}/' "$f" || return 1
  after=$(cat "$f")
  # Правка, ничего не изменившая, «применяется» молча: perl не жалуется на
  # несовпавший шаблон. Такая мутация объявляет сценарий беззубым по ложной
  # причине -- поэтому применение доказывается сравнением, а не кодом возврата.
  [[ "$after" != "$before" ]] || return 1
  # Круг 24, Н-1: замена, СЛОМАВШАЯ РАЗБОР жертвы, краснит сценарий не отключённым
  # механизмом, а синтаксической ошибкой -- и сверка следа этого не ловит, потому
  # что нечитаемый файл оставляет ровно тот же след, что и отключённый механизм
  # (перепись слепа в обоих случаях). Такая мутация доказывает не зубы, а только
  # что жертву можно испортить. Живой случай: образец `grep -Ev .*` съедал хвост
  # строки вместе с закрывающей `)`, а замена её не возвращала.
  # Неразбираемая жертва -- это КОД 2 «прибор не может мерить», отдельный от
  # кода 1 «мутация не применилась»: причины разные и чинятся по-разному.
  # Для *.sh страж гоняет и питоньи heredoc-тела (круг 25, E-1): bash -n их не
  # видит, а мутации целятся в питон внутри <<'ТЕГ' (fetch-corpus.sh, копии
  # стенда и зонда в снимке кита). Для *.py вложений тел под другим
  # интерпретатором НЕТ и искать их нечего -- проверено по живым жертвам
  # (corpus-list.py и укороченная копия checks-teeth.py): единственный внешний
  # вызов идёт файлом-скриптом через subprocess, а не встроенным текстом; если
  # у будущей .py-жертвы появится встроенное тело -- страж обязан вырасти и
  # на него.
  case "${MUT_FILE[$n]}" in
    *.sh|*.real) sh_victim_parses "$f" || return 2 ;;
    *.py) python3 -c 'import py_compile,sys; py_compile.compile(sys.argv[1], doraise=True)' \
            "$f" >/dev/null 2>&1 || return 2 ;;
  esac
  return 0
}

# Каталог состояния свипа выводится ровно там же, где его выводит
# run_sweep: выписанный вторым местом, он разошёлся, и сценарии замков
# держали чужой файл -- пройти они не могли в принципе. Заводятся
# ВМЕСТЕ: режим мутаций пересобирает окружение для каждой мутации.
use_corpus() { C="$1"; S="$C/corpus/state"; PLOCK="$C/corpus/patch.lock"; }

self_check() {
  local n reddened=0 broken=0
  for n in $(seq 1 $EXPECTED_MUTATIONS); do
    local kdir cdir before_failed
    kdir=$(mktemp -d "$ROOT/kit.XXXXXX"); cdir=$(mktemp -d "$ROOT/corp.XXXXXX")
    mk_kit "$kdir"; mk_corpus "$cdir"
    K="$kdir"; use_corpus "$cdir"
    local mrc=0
    mutate "$n" || mrc=$?
    if (( mrc == 2 )); then
      say "  ПРОВАЛ мутация $n сломала РАЗБОР ${MUT_FILE[$n]} -- замена невалидна,"
      say "         покраснение сценария ${MUT_SCENARIO[$n]} ничего не доказывает"
      broken=$((broken+1))
      rm -rf "$kdir" "$cdir"; continue
    elif (( mrc != 0 )); then
      say "  ПРОВАЛ мутация $n не применилась"
      rm -rf "$kdir" "$cdir"; continue
    fi
    before_failed=$FAILED
    LAST_EVID=""
    "scenario_${MUT_SCENARIO[$n]}"
    if (( FAILED > before_failed )); then
      if [[ "$LAST_EVID" == *"${MUT_CAUSE[$n]}"* ]]; then
        say "  ok     мутация $n покраснила сценарий ${MUT_SCENARIO[$n]} своей причиной"
        reddened=$((reddened+1))
      else
        say "  ПРОВАЛ мутация $n покраснила сценарий ${MUT_SCENARIO[$n]} ЧУЖОЙ причиной:"
        say "         ждали след «${MUT_CAUSE[$n]}», было: $(printf '%s' "$LAST_EVID" | tr '\n' '|' | cut -c1-300)"
      fi
      FAILED=$before_failed
    else
      say "  ПРОВАЛ мутация $n прошла МОЛЧА (сценарий ${MUT_SCENARIO[$n]} остался зелёным)"
    fi
    rm -rf "$kdir" "$cdir"
  done
  say "corpus-tools-bench: SELF-CHECK мутаций=$EXPECTED_MUTATIONS покраснели=$reddened"
  # Невалидная замена -- поломка САМОГО ПРИБОРА, а не вердикт о продукте: про
  # зубы такого сценария не сказано ничего ни в одну сторону. Класс 2 отделяет
  # это от класса 1 «мутация прошла молча» -- там измерение состоялось и дало
  # отрицательный ответ. Код 2 главнее: пока прибор чинят, остальным числам
  # этого прогона веры нет.
  (( broken == 0 )) || { say "  невалидных замен: $broken -- прибор чинится до следующего вердикта"; return 2; }
  (( reddened == EXPECTED_MUTATIONS )) || return 1
  return 0
}

if [[ "${1:-}" == "--self-check" ]]; then
  check_mut_tables || exit 4
  __rc=0; self_check || __rc=$?
  if (( __rc != 0 )); then __DONE=1; exit "$__rc"; fi
  __DONE=1; exit 0
fi

check_mut_tables || exit 4

# Свой рабочий корень: иначе стенд бьётся о замок ЖИВОГО прогона и пишет в его
# сводку. Каталог создаётся рядом с игрушечным корпусом и уходит вместе с ним.
# Бухгалтерия внешнего свипа СНИМАЕТСЯ, а не наследуется.
#
# С волны 21 стенд зовётся ИЗ свипа (предполёт), а свип экспортирует
# SWEEP_LEADER=1, SWEEP_KIT и SWEEP_SELF. Унаследовав их, игрушечный свип
# пропускал блок лидера: не делал своей копии, не уходил в свою сессию и брал
# ЧУЖОЙ SWEEP_KIT -- то есть настоящий кит вместо игрушечного. Измерено
# 2026-08-28: сценарии 9/16/18/19 покраснели ложно, «80-секундный» предполёт
# сорок минут гонял НАСТОЯЩИЕ сборки с настоящим tweakcc и зондом пути сборки
# по ЖИВОМУ ~/.tweakcc, и диск ушёл в ноль -- восстановление живого состояния
# не дописалось. Инструмент обязан мерить одно и то же, откуда бы его ни
# позвали.
SWEEP_ENV_SCRUB=(env -u SWEEP_LEADER -u SWEEP_KIT -u SWEEP_SELF -u SWEEP_LAST_N)

# Второй слой, и он ГЛАВНЫЙ. Скруббер выше защищает КАЖДЫЙ пусковой по
# отдельности -- то есть держится на памяти автора СЛЕДУЮЩЕГО пускового.
# 2026-08-30 эта память подвела: волна 25 добавила шестой пусковой (сценарий
# 87, S13) без скруббера, игрушечный свип унаследовал SWEEP_LEADER=1 настоящего
# свипа, пропустил блок лидера, перехватчик не был позван вовсе -- «прибор не
# мерит», -- и ПЕРВЫЙ настоящий предполёт после той волны отказал. Пин формы
# этого не видел ПО УСТРОЙСТВУ: он считает ИСПОЛЬЗОВАНИЯ скруббера, а
# пусковой, который скруббер ЗАБЫЛ, использований не добавляет.
#
# Снятие у СЕБЯ закрывает класс целиком: наследовать нечего, что бы ни забыл
# будущий пусковой. Скрубберы пусковых остаются вторым слоем -- они держат
# другой случай: переменную ставит сам сценарий (поведенческая половина
# сценария 66). Свои SWEEP_* стенд для собственной логики не читает.

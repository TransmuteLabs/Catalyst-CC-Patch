expect_refusal() {   # имя, ожидаемая подстрока, вывод, код
  local name=$1 want=$2 out=$3 rc=$4
  LAST_EVID="rc=$rc :: $out"
  if [[ $rc -eq 0 ]]; then
    bad "$name: код возврата 0, ждали отказ"; return
  fi
  if [[ "$out" != *"$want"* ]]; then
    bad "$name: в выводе нет «${want}»; было: $(printf '%s' "$out" | head -2 | tr '\n' ' ')"
    return
  fi
  ok "$name"
}

# Красная строка вердикта: прогон обязан назвать ИМЕННО эту причину и вернуть
# ненулевой код. Заглушка задаёт лог, сценарий -- ожидаемое слагаемое.
expect_red() {   # имя, режим заглушки, ожидаемая причина, [код заглушки]
  local name=$1 tweak=$2 want=$3 stub_rc=${4:-0} out rc
  out=$(STUB_TWEAK="$tweak" STUB_RC="$stub_rc" \
        run_sweep "$K" "$C/corpus" "$C/versions.txt" 900); rc=$?
  LAST_EVID="rc=$rc :: $out"
  if (( rc == 0 )); then
    bad "$name: код возврата 0 -- вердикт принял такой лог"; return
  fi
  if [[ "$out" != *"КРАСНАЯ: "*"$want"* ]]; then
    bad "$name: в вердикте нет причины «${want}»; было: $(printf '%s' "$out" | grep -a 'SWEEP 900' | head -1)"
    return
  fi
  ok "$name"
}

# Держатель считается готовым, когда замок ДЕЙСТВИТЕЛЬНО занят -- проба той же
# лестницей, а не истечение фиксированной паузы: под load 30-40 испытуемый
# доходил до замка уже после смерти держателя, и сценарий краснел по чужой
# причине -- «замок не занят», а не «дверь не работает».
LOCK_HOLD_BUDGET=15
wait_holder_ready() {   # файл замка; 0 -- держатель занял, 1 -- бюджет исчерпан
  local left=$LOCK_HOLD_BUDGET __hrc
  while (( left > 0 )); do
    perl -e 'use Fcntl ":flock"; open(my $fh, ">>", $ARGV[0]) or exit 2;
             exit(flock($fh, LOCK_EX|LOCK_NB) ? 0 : 1);' "$1" 2>/dev/null
    __hrc=$?
    (( __hrc == 1 )) && return 0
    sleep 1
    left=$(( left - 1 ))
  done
  say "corpus-tools-bench: ОТКАЗ -- держатель не занял замок $1 за ${LOCK_HOLD_BUDGET} c -- прибор не мерил" >&2
  return 1
}

# Мёртвый pid для сценариев-прополок: случайно ВЫБРАННЫЙ номер может оказаться
# живым, и проверка превратится в гонку с машиной.
dead_pid() {
  sh -c 'exit 0' &
  local pid=$!
  wait "$pid"
  printf '%s' "$pid"
}


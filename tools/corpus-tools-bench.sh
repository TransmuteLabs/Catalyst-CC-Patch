        bash "$probe" --table-check 2>&1); rc=$?
  LAST_EVID="rc=$rc :: $out"
  if (( rc == 0 )); then
    bad "43 рассинхрон таблиц: укороченная таблица принята (код 0)"; return
  fi
  if [[ "$out" != *"а мутаций"* ]]; then
    bad "43 рассинхрон таблиц: причина не названа; было: $(printf '%s' "$out" | head -1)"
    return

  LAST_EVID="rc=$rc :: $out :: временный=${__leftover:+ОСТАЛСЯ_ВРЕМЕННЫЙ }${__leftover:-убран} :: $(tr '\n' '|' < "$list")"
  if (( rc != 0 )); then

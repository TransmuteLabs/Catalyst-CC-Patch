#!/usr/bin/env bash
# Стенд корпусных инструментов: tools/sweep.sh, tools/fetch-corpus.sh и
# tools/corpus-list.py (общий дом формата списка).
#
# Зачем. Эти скрипты -- фундамент измерительной базы: свип решает, что и на чём
# мерить, наполнитель решает, какие байты считать эталонными, разбор списка
# решает, что вообще считается версией. Их гарантии держались на разовых ручных
# проверках, то есть на памяти человека; следующая правка снимала бы их
# беззвучно. Здесь они закреплены.
#
# Двери, которые стенд проверяет, срабатывают ДО первой сборки, поэтому корпус
# игрушечный (файлы в десятки байт), а вместо конвейера в копию кита кладётся
# ЗАГЛУШКА -- она печатает те же маркеры, по которым свип выносит вердикт, и
# позволяет задать любой их набор. Весь прогон занимает секунды и не трогает ни
# боевой корпус, ни боевой замок конвейера: дом корпуса, список версий,
# рабочий корень и путь замка берутся из CORPUS_DIR, CORPUS_LIST,
# SWEEP_STATE_DIR и CLAUDE_PATCH_LOCK.
#
# Сеть трогается в одном месте: сценарии наполнителя спрашивают реестр о
# заведомо несуществующей версии и получают отказ. При мёртвой сети они
# проходят так же -- проверено прогоном через закрытый порт как прокси.
#
# КОДЫ ВОЗВРАТА (подмножество общей конвенции кита, README «Exit codes»):
#   0 -- прогон зелёный: расхождений нет, беззубых правок нет
#   1 -- отказ по существу: сценарий разошёлся, мутация прошла молча,
#        прогон оборвался на полпути
#   2 -- прибор не может мерить: неизвестный режим в аргументах, пропавший
#        якорь вырезки
#   4 -- объявленное число не сходится с фактическим: длины пяти таблиц
#        мутаций или покрытие сценариев мутациями (тот же класс, что
#        EXPECTED_MUTATIONS у соседних стендов -- раунд 19, A-8)
#   3 -- мерить сейчас нельзя: замок стенда держит другой прогон стенда либо
#        идёт настоящая сборка (повторить позже)
#   6 -- машинерия замка сломана: не открыть файл замка, не работает perl
#        (повтор не поможет)
#
# Два режима:
#   bash tools/corpus-tools-bench.sh              -- прогон сценариев
#   bash tools/corpus-tools-bench.sh --self-check -- каждая мутация обязана
#                                                    покраснить свой сценарий
#                                                    И НАЗВАННОЙ ПРИЧИНОЙ
#   bash tools/corpus-tools-bench.sh --table-check -- только сверка длин таблиц
#   bash tools/corpus-tools-bench.sh --lock-probe  -- только встать в очередь
#                                                    на замок стенда
# Второй режим -- ответ на вопрос «а стенд вообще может упасть?». Беззубый
# стенд неотличим от рабочего, пока не назовёшь мутацию, которая его краснит.
# Мало и того: сценарий, покрасневший по ПОСТОРОННЕЙ причине (отказ соседней
# двери, упавший инструмент), доказывает чужое правило, а выглядит как зуб.
# Поэтому у каждой мутации записан след, который она обязана оставить в выводе.
set -u
KIT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
EXPECTED_SCENARIOS=86
EXPECTED_MUTATIONS=87

# Предусловие 1: параллельный прогон СТЕНДА.
#
# Заглушка конвейера называется claude-patch-all.sh -- иначе свип её не
# запустит. Значит, второй прогон стенда виден первому как «идёт настоящий
# прогон»: предусловие ниже объявило бы чужую заглушку боевой сборкой и
# отказало по неверно названной причине (а свипы внутри сценариев -- своим
# стражем выживших). Стенды поэтому выстраиваются в очередь на своём замке, и
# ожидание называется своим именем. Замок берётся ДО предусловия: наоборот
# порядок не помогает -- заглушки предыдущего прогона живы, пока он идёт.
__blk="${CORPUS_BENCH_LOCK:-${TMPDIR:-/tmp}/corpus-tools-bench.$(id -u).lock}"
__budget="${CORPUS_BENCH_LOCK_BUDGET:-300}"
# Не открыть файл замка -- сломана машинерия, а не занят замок: повтор через
# минуту даст то же самое, и вызывающий обязан это различать (код 6, не 3).
exec 9>"$__blk" || { echo "corpus-tools-bench: ОТКАЗ -- не открыть замок $__blk" >&2; exit 6; }
BLK_BUDGET="$__budget" perl -e '
  use Fcntl ":flock";
  open(my $fh, ">&=9") or exit 2;
  $SIG{ALRM} = sub { exit 1 };
  alarm($ENV{BLK_BUDGET} || 300);
  flock($fh, LOCK_EX) or exit 2;
  alarm(0); exit 0;'
__blk_rc=$?
if (( __blk_rc != 0 )); then
  if (( __blk_rc == 1 )); then
    echo "corpus-tools-bench: ОТКАЗ -- другой прогон стенда держит замок $__blk" >&2
    echo "  дольше ${__budget} c. Параллельно стенды не гоняются: заглушка второго" >&2
    echo "  прогона зовётся claude-patch-all.sh и выглядела бы боевой сборкой." >&2
    exit 3
  fi
  echo "corpus-tools-bench: ОТКАЗ -- не взять замок стенда (perl rc=$__blk_rc)" >&2
  echo "  Это отказ машинерии замка, а не занятый замок: повтор не поможет." >&2
  exit 6
fi

# Неизвестный режим -- отказ контракта вызова, а не тихий прогон сценариев:
# опечатка в `--self-chek` иначе давала бы зелёный прогон БЕЗ мутаций, и
# отчёт «стенд зелёный» означал бы не то, что читатель прочтёт.
case "${1:-}" in
  ''|--self-check|--table-check|--lock-probe) ;;
  *) echo "corpus-tools-bench: ОТКАЗ -- неизвестный режим «$1»" >&2
     echo "  режимы: (без аргументов) | --self-check | --table-check | --lock-probe" >&2
     exit 2 ;;
esac

# Зонд замка: взять очередь и выйти. Нужен сценарию, который проверяет,
# что второй прогон ЖДЁТ и называет причину: запускать вложенным весь стенд
# нельзя -- он дошёл бы до того же сценария и запустил себя снова.
if [[ "${1:-}" == "--lock-probe" ]]; then
  echo "corpus-tools-bench: замок стенда взят"
  exit 0
fi

# Предусловие 2: живой настоящий прогон.
#
# Свип отказывается стартовать, пока жив чужой claude-patch-all.sh или пишущая
# стадия tweakcc (обе -- и `--apply`, и `adhoc-patch`: вторую страж не видел, а
# пишет она в тот же образ) -- это ГЛОБАЛЬНЫЙ страж общего состояния, и подменять его
# ради стенда нельзя. Но тогда все сценарии свипа получают этот отказ вместо
# своего, и стенд краснеет по причине, не имеющей отношения к его предмету.
# Поэтому условие называется прямо и один раз, отдельным кодом возврата.
# Форма стража -- КАНОН свипа (tools/sweep.sh, «путь засчитывается, только если
# до него в командной строке нет ДРУГОГО скрипта»). Своя, более строгая форма
# здесь уже ловила гейт чисел (`python3 .docnum-gate.py <кит>/claude-patch-all.sh`)
# и отказывала стенду на чужом аргументе. Копия, а не общий файл: стенд обязан
# уметь краснеть от расхождения с каноном, а не наследовать его молча.
# Условие СНИМАЕТСЯ ЗАНОВО перед каждым сценарием, а не один раз на старте.
# Полный прогон идёт минуты, самопроверка -- десятки минут: настоящий прогон,
# начатый в это окно, ломал сценарии по своей причине, и читатель видел
# «стенд красный» вместо «мерить сейчас нельзя» (круг 21, F-3).
real_run_pids() {
  local __snap __alive __mine __p
  __snap=$(ps -eo pid,args)
  __alive=$(printf '%s\n' "$__snap" | awk '
  { for (i = 2; i <= NF && i <= 8; i++) {
      if ($i ~ /\.(py|js|mjs)$/) break
      if ($i ~ /claude-patch-all\.sh$/) { print $1; break } } }
  /catalyst-tweakcc.*index\.mjs.*(--apply|adhoc-patch)/ { print $1 }' || true)
  # Ниже -- НЕ часть стража, а вычитание СВОИХ: сценарий 45 сам поднимает
  # поддельный claude-patch-all.sh, чтобы проверить страж свипа, и канонический
  # страж обязан его увидеть -- а предусловие стенда обязано НЕ увидеть, иначе
  # стенд отказывает себе на собственной декорации (измерено полным прогоном:
  # «ПРОВАЛ 45 настоящий прогон конвейера не пойман» -- отказ шёл из
  # предусловия и подменял собой вывод свипа). Признак своего -- путь под временным
  # корнем стенда: ни один настоящий прогон оператора там не живёт. Вычитание
  # стоит ПОСЛЕ блока стража намеренно: сравнение форм (сценарий 57) режет
  # текст по «| awk '\''» и по «adhoc-patch», и всё, что ниже, в сравнение не
  # входит -- программа стража остаётся байт в байт канонической.
  __mine=$(printf '%s\n' "$__snap" | awk -v r="${ROOT:-}" '
    r != "" && index($0, r) { print $1 }' || true)
  for __p in $__alive; do
    printf '%s\n' "$__mine" | grep -qx "$__p" || printf '%s\n' "$__p"
  done
}

require_no_real_run() {   # $1 -- что шло дальше (для сообщения)
  local alive
  alive=$(real_run_pids)
  [[ -z "$alive" ]] && return 0
  # Отметка на диске, а не только `exit 3`.
  #
  # Предусловие снимается заново перед каждым игрушечным свипом, а свип всегда
  # зовут из подстановки команд (`out=$(run_sweep ...)`). `exit` внутри неё
  # кончает ТОЛЬКО подстановку: сценарий получал текст этого отказа как вывод
  # свипа и краснел своей формулировкой, а стенд ехал дальше -- ровно то, что
  # предусловие обязано было предотвратить. Отметка переживает подстановку, и
  # верхний уровень (ok/bad) прерывает прогон классом 3.
  [[ -n "${ROOT:-}" ]] && printf '%s\n' "$alive" > "$ROOT/.real-run"
  say "corpus-tools-bench: ОТКАЗ -- идёт настоящий прогон (pid: $alive)."
  say "  Стенд гоняет те же скрипты, и их же страж общего состояния tweakcc"
  say "  отказал бы каждому сценарию раньше проверяемой двери. Дождитесь конца."
  [[ -n "${1:-}" ]] && say "  Прервано перед: $1"
  exit 3
}

# Верхний уровень читает отметку и прерывает прогон целиком.
abort_if_real_run() {
  [[ -n "${ROOT:-}" && -e "${ROOT:-}/.real-run" ]] || return 0
  say "corpus-tools-bench: ОТКАЗ -- настоящий прогон начался посреди стенда (pid: $(tr '\n' ' ' < "$ROOT/.real-run"))."
  say "  Сценарии рядом с ним недостоверны: мерить сейчас нельзя, повторить позже."
  exit 3
}

# Ранний двойник `say`: настоящее определение ниже, а отказ предусловия
# случается раньше него.
say() { printf '%s\n' "$*"; }
require_no_real_run

ROOT=$(mktemp -d "${TMPDIR:-/tmp}/corpus-bench.XXXXXX")
# Часовой оборванного прогона: bash 3.2 отдаёт код 0, когда скрипт с
# EXIT-трапом умирает на фатальной ошибке ПОДСТАНОВКИ (unbound variable под
# `set -u`, `${x:?}`, bad substitution) -- провал невидим вызывающему
# (измерено 2026-08-28). Штатный конец объявляет себя, трап без объявления
# краснит сам.
__DONE=0
cleanup() {
  __rc=$?
  rm -rf "$ROOT"
  if [[ "${__DONE:-0}" != 1 && "$__rc" == 0 ]]; then
    echo "corpus-tools-bench: ОТКАЗ -- прогон оборвался, не дойдя до конца (ошибка оболочки выше)" >&2
    exit 1
  fi
  exit "$__rc"
}
trap cleanup EXIT

FAILED=0
RUN=0
# След последнего сценария: по нему --self-check требует от мутации ЕЁ причину.
LAST_EVID=""

say()  { printf '%s\n' "$*"; }
# Каждый сценарий кончается ok или bad -- это и есть точка, где верхний уровень
# видит отметку, оставленную предусловием внутри подстановки команд.
ok()   { abort_if_real_run; RUN=$((RUN+1)); say "  ok     $*"; }
bad()  { abort_if_real_run; RUN=$((RUN+1)); FAILED=$((FAILED+1)); say "  ПРОВАЛ $*"; }

# --- игрушечный корпус -------------------------------------------------------
# Версии названы заведомо несуществующими в реестре: если сценарий всё же
# дойдёт до сети, он получит отказ, а не чужой образ.
# Содержимое игрушечного образа -- ОДИН дом.
#
# Оно было записано в пяти местах: в наполнении корпуса и в 4 сценариях
# docnum:subset,
# которые портят образ и восстанавливают его литералом. Когда образу добавили
# номер версии (заглушка обязана отвечать про НЕГО), восстановления вернули
# старый текст -- пин перестал сходиться, и 22 сценария docnum:historical подряд
# покраснели по чужой причине. Одна функция: сменить содержимое можно только
# сразу везде.
toy_image() {   # путь, версия
  printf 'образ %s\n' "$2" > "$1"
}

mk_corpus() {   # каталог-назначение
  local dir=$1
  mkdir -p "$dir/corpus"
  # Образ НЕСЁТ свою версию: заглушка конвейера читает её оттуда и печатает
  # строку дыма про НЕЁ. С константой в заглушке поле вердикта, привязанное к
  # номеру версии, проверялось бы на выдуманном номере.
  toy_image "$dir/corpus/0.0.900.pristine" 0.0.900
  toy_image "$dir/corpus/0.0.901.pristine" 0.0.901
  local h900 h901
  h900=$(shasum -a 256 "$dir/corpus/0.0.900.pristine" | awk '{print $1}')
  h901=$(shasum -a 256 "$dir/corpus/0.0.901.pristine" | awk '{print $1}')
  # Платформа называется и здесь: разбор списка её ТРЕБУЕТ, и игрушечный
  # список без неё проверял бы дверь платформы, а не свой предмет.
  local plat
  plat=$(cd "$KIT" && python3 -c 'import claude_patch; print(claude_patch.npm_platform_pkg())')
  { echo "# игрушечный список стенда"
    echo "# platform: $plat"
    echo "900 0.0.900 $h900"
    echo "901 0.0.901 $h901"
  } > "$dir/versions.txt"
  # Производные списки заводятся один раз, рядом с основным.
  grep -v '^# platform:' "$dir/versions.txt" > "$dir/versions.noplat.txt"
  { echo "# platform: $plat"
    echo "900 0.0.900 $h900"
    echo "900b 0.0.900 $h900"
  } > "$dir/versions.dup.txt"
  { echo "# platform: $plat"
    echo "900 0.0.900 $h900 лишнее"
  } > "$dir/versions.extra.txt"
  { echo "# platform: $plat"
    echo "900 0.0.900 $(printf '%s' "$h900" | tr 'a-f' 'A-F')"
  } > "$dir/versions.upper.txt"
  { echo "# platform: @anthropic-ai/claude-code-и-не-эта-машина"
    echo "900 0.0.900 $h900"
  } > "$dir/versions.foreign.txt"
  # Дубль МЕТКИ при РАЗНЫХ версиях: дубль версии ловит соседняя дверь, и список
  # с обоими совпадениями доказывал бы её, а не эту.
  { echo "# platform: $plat"
    echo "900 0.0.900 $h900"
    echo "900 0.0.901 $h901"
  } > "$dir/versions.duplabel.txt"
  # Пин из 63 знаков -- не «-» и не 64 знака.
  { echo "# platform: $plat"
    echo "900 0.0.900 ${h900:0:63}"
  } > "$dir/versions.badpin.txt"
  # Версия с буквой: имя файла из неё считалось бы молча.
  { echo "# platform: $plat"
    echo "900 0.0.900 $h900"
    echo "90x 0.0.90x $h901"
  } > "$dir/versions.badver.txt"
}

# Копия кита под мутации: сценарии всегда гоняют скрипты ИЗ НЕЁ, поэтому режим
# мутаций отличается от обычного ровно одной правкой в копии.
mk_kit() {   # каталог-назначение
  local dir=$1
  mkdir -p "$dir"
  cp -R "$KIT"/. "$dir"/
  # Конвейер игрушечного кита -- ЗАГЛУШКА.
  #
  # Двери, которые проверяет стенд, срабатывают ДО первой сборки, но мутации,
  # эти двери отключающие, пускали свип дальше -- в НАСТОЯЩИЙ конвейер: он брал
  # боевой замок, лез в сеть за распаковщиком и упирался в игрушечную цель.
  # Безопасность держалась на его раннем отказе, который стенд не пинил.
  #
  # Заглушка печатает РОВНО те маркеры, по которым свип считает поля вердикта,
  # и умеет убрать любой из них (STUB_TWEAK) или вернуть любой код (STUB_RC).
  # Так каждое слагаемое вердикта получает свой сценарий и свою мутацию.
  cat > "$dir/claude-patch-all.sh" <<'STUB'
#!/usr/bin/env bash
# Заглушка конвейера для tools/corpus-tools-bench.sh. Печатает маркеры, по
# которым свип считает поля вердикта. STUB_TWEAK убирает один маркер (или
# добавляет [FAIL]/NUL), STUB_RC задаёт код возврата, STUB_TAMPER портит
# названный файл -- так проверяется сверка КОПИИ, сделанной после сверки пинов.
set -u
tweak="${STUB_TWEAK:-none}"
# Цель читается ИЗ АРГУМЕНТОВ: два поля вердикта -- версия и дайджест --
# привязаны к тому, что конвейеру передали, и заглушка обязана отвечать про
# ЭТОТ файл, а не про константу. `--expect-sha` она принимает и молчит: свою
# дверь пина настоящий конвейер закрывает сам (проверено прямым прогоном), а
# стенд здесь меряет ВЕРДИКТ СВИПА.
target=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --target)     target="${2:-}"; shift 2 ;;
    --expect-sha) shift 2 ;;
    *)            shift ;;
  esac
done
unless() { [[ "$tweak" == "$1" ]] || printf '%s\n' "$2"; }
[[ -z "${STUB_TAMPER:-}" ]] || printf 'подменённые байты\n' > "$STUB_TAMPER"
# STUB_LINGER: оставить за собой ЖИВОЙ процесс, чей путь ведёт в снимок кита.
# Так проверяется, что свип не сносит снимок из-под ещё исполняющегося
# конвейера (круг 21, F-9). Путь снимка попадает в аргументы через $0.
#
# Две команды через `;`, а не одна: `bash -c 'sleep 25' "$0"` -- ПРОСТАЯ
# команда, и bash заменяет себя на неё через exec (измерено 2026-08-28). В
# `ps` остаётся `sleep 25` БЕЗ пути снимка, жильца никто не видит, и сценарий

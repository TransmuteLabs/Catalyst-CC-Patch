mk_lastn_corpus() {   # каталог
  local d=$1 v plat h
  rm -rf "$d"; mkdir -p "$d/corpus"
  plat=$(grep '^# platform:' "$C/versions.txt")
  { echo "# игрушечный список набора"
    echo "$plat"
    # Порядок строк НЕ по номеру: свип обязан брать последние по ВЕРСИИ, а не

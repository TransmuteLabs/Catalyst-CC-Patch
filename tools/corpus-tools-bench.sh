  out=$(SRC_KIT="$repo" bash -c "$fn
kit_state")
  if [[ "$out" == *"+dirty"* ]]; then
    LAST_EVID="метка=[$out]"
    ok "8 метка происхождения видит неотслеживаемый файл"
  else

#!/usr/bin/env bash
# Общий дом рецепта фикстуры: копия образа, приведённая к конвейерному
# пред-состоянию (нейтрализация двух чтений tengu_passport_quail -- то, что
# стадия tweakcc --apply делает ДО нашего шага), с последующим применением
# нашего патча (механизм K1 разбора #407).
# CONSTRAINT: единственный экземпляр рецепта в дереве -- стенд шага 7
# (tools/step7-window-teeth.sh) и прибор зубов (tools/checks-teeth.py) зовут
# ЭТОТ дом; вторая копия рецепта расходится молча (Ф5 #407).
# Коды выхода (подмножество общей таблицы кита):
#   0  предмет построен
#   2  прибор не может построить: аргументы, ПИН «Replaced 2 occurrence(s)»
#      не сошёлся, прогон патча отказал ИЛИ прошёл без строки применения,
#      копия предмета не создана
#   3  НЕ ИЗМЕРЕНО: на машине нет инструментария (node, форк, образ, патч)
# CONSTRAINT: на маке нет timeout -- каждый прогон node обёрнут perl-alarm:
# зависший воркер обязан отказать, а не молчать.
# CONSTRAINT: вывод прогона ловится в переменную (2>&1) в ОБЕИХ ветках --
# он пинится содержательной строкой и входит в текст отказа; после
# успешного пина apply печатает его вызывающему (стенд шага 7 пинит свои
# строки по логу прогона).
# CONSTRAINT: ни один путь отказа не выходит кодом вне {0,2,3} --
# незащищённый cp уже отдавал голую единицу мимо таблицы кита, а
# незащищённая печать причины на закрытом дескрипторе отдавала единицу
# ВМЕСТО 2/3 (Х3 #407: квантор держится печатью refuse/absent и Ф9).
set -euo pipefail

FORK="${FORK:-$HOME/work/SIB/Transmutation/Nexus/Catalyst/Catalyst-tweakcc/dist/index.mjs}"
RUN_TIMEOUT=420

# CONSTRAINT (Х3 fix-волны #407, раунд 3): печать причины не имеет права
# уносить код выхода за объявленное множество {0,2,3}. Закрытый stderr даёт
# печати EBADF, закрытый пайп -- SIGPIPE; и то и другое под `set -e` убивало
# скрипт ДО `exit 2/3`, и различение «нечем построить» (2) от «инструментария
# нет» (3) пропадало у потребителя вместе с кодом. Тот же вектор, что Ф9
# закрыла для stdout, поэтому и лечение то же: игнор SIGPIPE плюс `|| true`.
# Игнор ставится ПЕРЕД печатью и не снимается: скрипт всё равно выходит здесь.
refuse() {  # код 2: построить предмет нечем
  trap '' PIPE
  echo "fixture-build: ОТКАЗ -- $1" >&2 || true
  exit 2
}

absent() {  # код 3: инструментария нет -- НЕ ИЗМЕРЕНО
  trap '' PIPE
  echo "fixture-build: НЕ ИЗМЕРЕНО -- $1" >&2 || true
  exit 3
}

run_node() {  # часовой прогона: perl-alarm вокруг node (timeout на маке нет)
  perl -e 'alarm shift; exec @ARGV' "${RUN_TIMEOUT}" "$@"
}

need_node() {
  command -v node > /dev/null 2>&1 || absent "нет node"
  [[ -f "${FORK}" ]] || absent "нет форка ${FORK}"
}

case "${1:-}" in
  neutralize)
    [[ $# -eq 3 ]] || refuse "neutralize: ровно два аргумента (образ, выход), дано $(( $# - 1 ))"
    image=$2; out=$3
    [[ -f "${image}" ]] || absent "нет образа ${image}"
    need_node
    cp "${image}" "${out}" || refuse "neutralize: копия образа не создана: ${out}"
    NEUT_RC=0
    NEUT_OUT=$(run_node node "${FORK}" adhoc-patch \
      --string 'P("tengu_passport_quail",!1)' '!0' \
      -p "${out}" \
      --confirm-possible-dangerous-patch 2>&1) || NEUT_RC=$?
    if [[ "${NEUT_RC}" -ne 0 ]]; then
      refuse "нейтрализация не применилась (rc=${NEUT_RC}): ${NEUT_OUT}"
    fi
    # ПИН: ровно 2 вхождения -- extraction gate и extract-mode predicate;
    # иное число значит другой предмет, мерить им нельзя (Ф2 #407).
    if [[ "${NEUT_OUT}" != *"Replaced 2 occurrence(s)"* ]]; then
      refuse "нейтрализация легла не двумя заменами: ${NEUT_OUT}"
    fi
    ;;
  apply)
    [[ $# -eq 4 ]] || refuse "apply: ровно три аргумента (скрипт-патч, нейтрализованный, выход), дано $(( $# - 1 ))"
    script=$2; neutralized=$3; out=$4
    [[ -f "${script}" ]] || absent "нет скрипта патча ${script}"
    [[ -f "${neutralized}" ]] || absent "нет нейтрализованного образа ${neutralized}"
    need_node
    cp "${neutralized}" "${out}" || refuse "apply: копия предмета не создана: ${out}"
    APPLY_RC=0
    APPLY_OUT=$(run_node node "${FORK}" adhoc-patch \
      --script "@${script}" -p "${out}" \
      --confirm-possible-dangerous-patch 2>&1) || APPLY_RC=$?
    if [[ "${APPLY_RC}" -ne 0 ]]; then
      refuse "патч не применился к копии (rc=${APPLY_RC}): ${APPLY_OUT}"
    fi
    # CONSTRAINT (Р5/Ф8 fix-волны #407): пин применения -- ЦЕЛАЯ строка
    # «✓ Script patch applied to <путь предмета>» (якоря начала и конца
    # строки), а не вхождение подстроки: форк, напечатавший фразу внутри
    # предупреждения, уже проходил пин, не применив ничего. Строка называет
    # ПУТЬ НАШЕГО выхода -- предупреждение чужого вывода его не знает.
    # Путь берётся ФИЗИЧЕСКИЙ (cd -P): форк печатает разрешённый путь
    # (измерено: /var -> /private/var, двойной слеш TMPDIR схлопывается),
    # а сырой аргумент разошёлся бы с ним молча. Пин доказывает, что форк
    # СКАЗАЛ «применил».
    __pin_dir=$(cd -P "$(dirname "${out}")" && pwd -P) \
      || refuse "apply: не разрешить каталог предмета: $(dirname "${out}")"
    __pin="✓ Script patch applied to ${__pin_dir}/$(basename "${out}")"
    __applied=0
    while IFS= read -r __line; do
      if [[ "${__line}" == "${__pin}" ]]; then __applied=1; fi
    done <<< "${APPLY_OUT}"
    if [[ "${__applied}" -ne 1 ]]; then
      refuse "прогон патча без строки применения целой строкой: ${APPLY_OUT}"
    fi
    # CONSTRAINT (Ф8 fix-волны #407): сравнение предмета ДО и ПОСЛЕ -- пин
    # строки доказывает, что форк сказал «применил», а сравнение -- что он
    # ПРИМЕНИЛ: тождество байтов при коде 0 -- отказ с собственным текстом.
    if cmp -s "${neutralized}" "${out}"; then
      refuse "форк отчитался применением, а предмет побайтово не изменился: ${APPLY_OUT}"
    fi
    # CONSTRAINT (Ф9 fix-волны #407): печать пойманного вывода не имеет права
    # выносить код за объявленное множество {0,2,3}: потребитель, закрывший
    # stdout, доставляет печати SIGPIPE (измерено rc=141), закрытый
    # дескриптор -- rc=1. Игнор SIGPIPE не снимается до конца скрипта: bash
    # доигрывает отложенный SIGPIPE на выходе, если вернуть ему умолчание
    # (измерено: снятие ловушки возвращает 141).
    trap '' PIPE
    printf '%s\n' "${APPLY_OUT}" || true
    ;;
  *)
    refuse "подкоманда neutralize|apply, дано: ${1:-пусто}"
    ;;
esac
exit 0

LOCK_BUDGET=${SWEEP_LOCK_BUDGET:-600}
LOCK_POLL=15

# Дом tweakcc НА ВРЕМЯ СВИПА -- свой.
#
# Каждая сборка свипа проходит через распаковщик, а тот держит в своём доме
# бэкап образа и запись о версии. Пока дом был живым, свип уносил ТОЧКУ
# ВОССТАНОВЛЕНИЯ живой установки: замер 2026-08-28 посреди прогона показал в
# `native-binary.backup` байты корпусной версии, а в `ccInstallationPath` --
# временный каталог. Зелёный SWEEP DONE оставлял дом настроенным на последнюю
# версию набора, и `tweakcc --restore` после такого прогона ударил бы в живую
# установку чужим образом (круг 21, линза E, находка 1).
#
# Дом СЕМЕНИТСЯ из живого: настройки решают, какие патчи применяются, и свип
# обязан мерить ТОТ ЖЕ набор, а не пустой профиль. Копия делается клоном APFS
# (`cp -Rc`, общие блоки -- 116 МБ кэша промтов не занимают места и не
# копируются побайтно); там, где клон не поддержан, идёт обычная копия, и это
# объявляется. Живой дом после этого не открывается на запись НИ РАЗУ.
SWEEP_TW_HOME="$STATE/tweakcc-home"
if [[ -z "${SWEEP_KEEP_LIVE_TWEAKCC:-}" ]]; then
  __live_tw="${TWEAKCC_CONFIG_DIR:-}"
  if [[ -z "$__live_tw" ]]; then
    if [[ -d "$HOME/.tweakcc" ]]; then __live_tw="$HOME/.tweakcc"
    elif [[ -d "$HOME/.claude/tweakcc" ]]; then __live_tw="$HOME/.claude/tweakcc"
    elif [[ -n "${XDG_CONFIG_HOME:-}" ]]; then __live_tw="$XDG_CONFIG_HOME/tweakcc"
    else __live_tw="$HOME/.tweakcc"
    fi
  fi
  rm -rf "$SWEEP_TW_HOME"
  if [[ -d "$__live_tw" ]]; then
    if /bin/cp -Rc "$__live_tw" "$SWEEP_TW_HOME" 2>/dev/null; then
      echo "SWEEP дом tweakcc: клон живого ($__live_tw) -> $SWEEP_TW_HOME"
    elif /bin/cp -R "$__live_tw" "$SWEEP_TW_HOME"; then
      echo "SWEEP дом tweakcc: КОПИЯ живого (клон не поддержан ФС) -> $SWEEP_TW_HOME"
    else
      echo "SWEEP ОТКАЗ: не сделать свой дом tweakcc из $__live_tw" >&2
      sum_line "# дом tweakcc: НЕ СОЗДАН -- прогон отменён"
      exit 1
    fi
  else
    mkdir -p "$SWEEP_TW_HOME"
    echo "SWEEP дом tweakcc: живого дома нет, создан пустой $SWEEP_TW_HOME"
  fi
  export TWEAKCC_CONFIG_DIR="$SWEEP_TW_HOME"
  sum_line "# дом tweakcc: свой ($SWEEP_TW_HOME), живой не трогается"
else
  # Объявленный пропуск: без объявления это ровно то молчание, против которого
  # заведён сам механизм.
  echo "SWEEP дом tweakcc: ЖИВОЙ по ручке SWEEP_KEEP_LIVE_TWEAKCC=${SWEEP_KEEP_LIVE_TWEAKCC}"
  sum_line "# дом tweakcc: ЖИВОЙ по ручке -- прогон правит живое состояние"
fi

declare -a UNMEASURED=()
RED=0
for entry in "${SRC[@]}"; do
  v="${entry%%:*}"; ver=$(ver_of "$entry"); src=$(src_of "$ver"); want=$(pin_of "$entry")
  # Точки в номере версии экранируются: шаблон идёт в grep как РЕГУЛЯРНОЕ
  # выражение, и «2.1.246» без экранирования сошлось бы и с «2X1Y246».
  ver_rx="${ver//./\\.}"
  log="$STATE/log/sweep-$v.log"
  locklog="$STATE/log/sweep-$v.lock.log"
  rm -f "$log" "$locklog"
  # Меряется КОПИЯ, а пин доказывал исходник. Между сверкой и этим местом
  # проходят минуты и целые сборки: упавший `cp` (нет места, нет прав,
  # обломок прошлого прогона под тем же именем) или подменённый за это время
  # исходник давали измерение чужих байт под именем запинованной версии, и
  # прогон объявлял его зелёным. Сверяется то, что пойдёт в конвейер, и в тот
  # момент, когда оно туда пойдёт.
  if ! cp -p "$src" "$STATE/bin/$v.wave.bin"; then
    RED=$(( RED + 1 ))
    echo "SWEEP $v: КРАСНАЯ -- не скопировать $src в $STATE/bin/$v.wave.bin"
    sum_line "$v КРАСНАЯ (копия не сделана)"
    continue
  fi
  if ! copy=$(sha256_of "$STATE/bin/$v.wave.bin"); then
    RED=$(( RED + 1 ))
    echo "SWEEP $v: КРАСНАЯ -- не прочитать копию $STATE/bin/$v.wave.bin"
    sum_line "$v КРАСНАЯ (копия не читается)"
    continue
  fi
  if [[ "$copy" != "$want" ]]; then
    RED=$(( RED + 1 ))
    echo "SWEEP $v: КРАСНАЯ -- копия не сходится с пином (пин $want, копия $copy)"
    sum_line "$v КРАСНАЯ (копия не сходится с пином)"
    continue
  fi
  waited=0
  while :; do
    # Пин передаётся ВНУТРЬ конвейера: вопрос «те ли это байты» задаёт тот, кто
    # файл читает, и в момент чтения. Сверка копии выше доказывает файл на
    # момент `cp`, а конвейер доберётся до него минутами позже.
    # Пристинный близнец для гейта пола -- корпусный образ этой же версии: на
    # пути `--target` `.orig` рядом с копией не бывает, и без ручки гейт
    # пропускался бы на КАЖДОЙ версии свипа, то есть везде, где он и нужен.
    # CLAUDE_PATCH_SKIP_MODELS=1 -- объявленный пропуск: единственный
    # автоматический прогон настоящих сборок НИКОГДА не гоняет sync цен, и
    # объявление об этом жило только в логе версии (раунд 18, G-1).
    # Люки конвейера снимаются ЗДЕСЬ, по тому же правилу, по которому стенд
    # снимает бухгалтерию свипа: прогон обязан мерить КИТ, а не среду
    # оператора. Унаследованные TWEAKCC_LOCAL/CATALYST_TWEAKCC_* молча меняют
    # сам патчер (сводка при этом неотличима от эталонной), SKIP_BENCH и
    # GATE_BUDGET снимают и ослабляют гейты, ALLOW_TWEAKCC_FAILURES отменяет
    # фатальность падения tweakcc, SIGN_ID меняет подпись артефакта
    # (раунд 19, В-4 и В-5). PROBE_CFG_LOAN снимает стража маркера конфига
    # tweakcc: его объявляет ЗОНД про свой собственный заём, и унаследованный
    # от оператора он молча распространил бы это объявление на сборки свипа,
    # которые ничего не одалживали (волна 32, W-4).
    # CLAUDE_PATCH_LOCK НЕ снимается: им стенд уводит
    # игрушечные прогоны с боевого замка.
    env -u CLAUDE_PATCH_ALLOW_TWEAKCC_FAILURES -u CLAUDE_PATCH_SKIP_BENCH \
        -u CLAUDE_PATCH_GATE_BUDGET -u CLAUDE_PATCH_SIGN_ID -u TWEAKCC_LOCAL \
        -u CATALYST_TWEAKCC_REPO -u CATALYST_TWEAKCC_SHA \
        -u CLAUDE_PATCH_PROBE_CFG_LOAN \
      CLAUDE_PATCH_SKIP_MODELS=1 CLAUDE_PATCH_FLOOR_IMAGE="$src" \
      bash "$HERE/claude-patch-all.sh" \
      --target "$STATE/bin/$v.wave.bin" --expect-sha "$want" > "$log" 2>&1 8>&-
    rc=$?
    (( rc == 3 )) || break
    # Отдельный файл: повтор перезаписывает лог версии, и снятый срез иначе
    # исчез бы вместе с ним -- ровно так и потерялся держатель в прошлый раз.
    {
      echo "=== $(date '+%F %T') замок занят, ждём (прождано ${waited}s из ${LOCK_BUDGET}s) ==="
      echo "--- lsof $PATCH_LOCK ---"
      lsof "$PATCH_LOCK" 2>/dev/null || echo "(lsof не назвал никого)"
      # Срез ps -- ДОПОЛНЕНИЕ к lsof, и он обрезан по длине и числу строк.
      # Подстрока «claude-patch-all» встречается и в командной строке оболочки,
      # которая свип запустила: первый же снимок принёс многокилобайтную строку
      # с чужим окружением вместо имени держателя. lsof называет держателя
      # точно, ps лишь показывает соседей.
      echo "--- ps: конвейер и tweakcc (обрезано) ---"
      ps -eo pid,ppid,pgid,etime,args \
        | grep -E 'claude-patch-all|catalyst-tweakcc|--apply' | grep -v grep \
        | cut -c1-200 | head -20 \
        || echo "(таких процессов нет)"
    } >> "$locklog"
    (( waited >= LOCK_BUDGET )) && break
    sleep "$LOCK_POLL"; waited=$(( waited + LOCK_POLL ))
  done
  # Все поля считаются в локали C.
  #
  # Измерено 2026-08-28: /usr/bin/grep на файле с НУЛЕВЫМ БАЙТОМ (а такой лог
  # штатно бывает -- поле «лог смешан с чужим потоком» ровно про него) считает
  # НЕ-ASCII образец нулём, оставляя ASCII-образцы рабочими. То есть поля с
  # русским текстом и с «✓» молча читались как отсутствующие, и вердикт
  # объявлял неотработавшим гейт, который отработал. В локали C образец --
  # последовательность байт, и разбор от содержимого лога не зависит.
  # Локаль вызывающего сохраняется и возвращается: `unset` уничтожал ЧУЖОЕ
  # значение, и вторая версия прогона собиралась уже в другой локали, чем
  # первая (раунд 19, В-9).
  __lc_was="${LC_ALL+set}"; __lc_prev="${LC_ALL:-}"
  export LC_ALL=C
  ok=$(num "$(grep -a -c '\[OK\]' "$log")")
  fail=$(num "$(grep -a -c '\[FAIL\]' "$log")")
  tw=$(num "$(grep -a -c '^    ✓ ' "$log")")
  ours=$(num "$(grep -a -c 'Script patch applied' "$log")")
  # Прогон tweakcc кончается ОДНИМ из двух баннеров: полным («successfully»)
  # или частичным («with some failures»). Частичный законен только рядом с
  # NOTE конвейера об объявленных непроходах (tools/tweakcc-known-misses.txt):
  # без неё конвейер отказал бы сам. Считать прогоном лишь полный баннер --
  # значит читать законный частичный прогон как «прогонов 0» (257, волна 33).
  twok=$(num "$(grep -a -c 'Customizations applied successfully' "$log")")
  twpart=$(num "$(grep -a -c 'Customizations applied with some failures' "$log")")
  twnote=$(num "$(grep -a -c '^NOTE: объявленные непроходы tweakcc на ' "$log")")
  twruns=$(( twok + twpart ))
  iface=$(num "$(grep -a -c '^Interface:' "$log")")
  # Поле привязано к НОМЕРУ версии, а не к форме строки. Прежде оно считало
  # строки по шаблону `^Version: .*(Claude Code)`, поэтому сборка, объявившая
  # ЛЮБУЮ другую версию, проходила вердикт зелёной под именем запинованной.
  smoke=$(num "$(grep -a -c "^Version: $ver_rx (Claude Code)" "$log")")
  # А это -- ответ конвейера на вопрос о происхождении байт: он печатает
  # дайджест того, из чего собирал. Совпадение с пином связывает вердикт с
  # БАЙТАМИ, а не только с именем файла, который мы ему назвали.
  digest=$(num "$(grep -a -c "^Source digest: $want " "$log")")
  bench=$(num "$(grep -a -c '^Probes: .* scenarios behaved as specified' "$log")")
  # Локаль возвращается сразу после последнего поля: дальше идут сообщения
  # оператору, и вердикт печатается его текстом, а не байтами.
  # Присутствие ВЫЗОВА гейта иначе не пинится ничем: удали из конвейера блок,
  # зовущий гейт форм оболочки или пол утверждений, -- и не покраснеет ни один
  # стенд (сам гейт уехал вместе со своей проверкой). Вердикт свипа требует их
  # итоговых строк, то есть доказательства, что гейт ИСПОЛНЯЛСЯ на этой сборке.
  # У пола засчитывается и объявленный пропуск: пристинный близнец есть не
  # всегда, а объявление -- это тоже ответ вызова.
  forms=$(num "$(grep -a -c '^ФОРМЫ ОБОЛОЧКИ ЧИСТЫ' "$log")")
  floor=$(num "$(grep -a -c -E '^ПОЛ ПРОВЕРОК СОШЁЛСЯ|^==> Пол проверок ПРОПУЩЕН' "$log")")
  # A NUL byte means two writers shared this file: the log is not one run.
  mixed=$(LC_ALL=C tr -d '\000' < "$log" | wc -c | tr -d ' ')
  size=$(wc -c < "$log" | tr -d ' ')
  if [[ "$__lc_was" == set ]]; then export LC_ALL="$__lc_prev"; else unset LC_ALL; fi
  note=""
  if (( rc == 3 )); then
    note=" НЕ ИЗМЕРЕНО(замок, ждали ${waited}s; держатели: $locklog)"
    UNMEASURED+=("$v")
  fi
  # Вердикт ПОТРЕБЛЯЕТ всё, что измерено.
  #
  # Прежде в него входил один код возврата, а счётчики оставались текстовой
  # припиской: лог, смешанный с чужим потоком (NUL), два применения патчей
  # вместо одного, ноль прошедших проверок, упавшая проверка, непройденный
  # дым, интерфейс или стенд зондов -- всё это печаталось и не мешало
  # последней строке сказать «красных нет» с нулевым кодом. То есть инцидент,
  # ради которого счётчики и заводились (выживший ребёнок допатчивает образ
  # ПОСЛЕ проверки), выглядел зелёным прогоном.
  #
  # Версия, не измеренная из-за замка, считается ОДИН раз, в своём счётчике:
  # её лога нет, и поля к ней не применяются.
  if (( rc != 3 )); then
    declare -a why=()
    if (( rc != 0 )); then
      case $rc in
        2) why+=("конвейер вернул 2: контракт вызова нарушен или прибор гейта не мерил") ;;
        # Круг 28, F-6(а): прежний текст называл ТОЛЬКО байты против пина, а
        # класс 4 у конвейера стал шире (полоса F снимает схлопывание класса 4
        # стендов в единицу) -- длина/покрытие таблицы мутаций стенда входит в
        # тот же класс «объявленное число не сошлось с фактическим».
        4) why+=("конвейер вернул 4: объявленное число не сошлось с фактическим — байты цели против пина либо длина/покрытие таблицы мутаций стенда") ;;
        6) why+=("конвейер вернул 6: замок/окружение сломаны -- ждать бесполезно") ;;
        *) why+=("конвейер вернул $rc") ;;
      esac
    fi
    [[ "$mixed" == "$size" ]] || why+=("лог смешан с чужим потоком (NUL)")
    [[ "$fail" == "0" ]] || why+=("проверок упало $fail")
    [[ "$ok" != "0" ]] || why+=("ни одной прошедшей проверки")
    [[ "$ours" == "1" ]] || why+=("наших применений $ours")
    [[ "$twruns" == "1" ]] || why+=("прогонов tweakcc $twruns")
    [[ "$twpart" == "0" || "$twnote" == "1" ]] || why+=("частичный прогон tweakcc без объявленных непроходов")
    # Один прогон tweakcc, применивший НОЛЬ патчей, до волны 22 уходил зелёным:
    # поле `tw` печаталось в сводке, но ни одно утверждение его не читало
    # (раунд 19, В-15). Порог -- «хоть один», а не число: у версий 247+ промтов
    # в рантайме нет, и патчей честно меньше.
    [[ "${tw:-0}" != "0" ]] || why+=("tweakcc не применил ни одного патча")
    [[ "$smoke" == "1" ]] || why+=("дым не подтверждён для $ver")
    [[ "$digest" == "1" ]] || why+=("конвейер не объявил запинованные байты")
    [[ "$iface" == "1" ]] || why+=("интерфейс не подтверждён")
    [[ "$bench" == "1" ]] || why+=("стенд зондов не подтверждён")
    [[ "$forms" == "1" ]] || why+=("гейт форм оболочки не отработал")
    [[ "$floor" == "1" ]] || why+=("пол утверждений не отработал")
    if (( ${#why[@]} )); then
      RED=$(( RED + 1 ))
      note="$note КРАСНАЯ: $(printf '%s; ' "${why[@]}")"
    fi
  fi
  # Зубы по первому собранному образу ЭТОГО прогона. rc!=3 -- конвейер
  # дошёл до конца (не замок); файл ещё на месте, зелёную копию снесём ниже.
  # Прибор мутирует КОПИЮ (shutil.copyfile), сам файл только читается.
  if (( TEETH_DONE == 0 )) && (( rc != 3 )) && [[ -f "$STATE/bin/$v.wave.bin" ]]; then
    python3 "$TEETH_PY" --image "$STATE/bin/$v.wave.bin" 8>&- > "$TEETH_LOG" 2>&1
    __trc=$?
    TEETH_DONE=1
    case $__trc in
    0) echo "SWEEP зубы реестра проверок: ЗЕЛЁНО (лог $TEETH_LOG)"
       sum_line "# зубы реестра проверок: ЗЕЛЁНО" ;;
    5) echo "SWEEP зубы реестра проверок ПРОПУЩЕНЫ: на машине нет собранного образа"
       sum_line "# зубы реестра проверок: ПРОПУЩЕНЫ -- нечего мерить" ;;
    3) # Не красный прогон, а НЕИЗМЕРЕННЫЙ: живая сборка меняет образ под
       # руками прибора. Класс 3 всей таблицы кита -- «повтор поможет».
       echo "SWEEP ОТКАЗ: зубы реестра НЕ ИЗМЕРЕНЫ -- замок конвейера держит живая сборка (лог $TEETH_LOG)" >&2
       tail -3 "$TEETH_LOG" >&2
       sum_line "# зубы реестра проверок: НЕ ИЗМЕРЕНЫ -- занят замок конвейера"
       exit 3 ;;
    2) if grep -q 'КОНТРОЛЬ ПРОВАЛЕН' "$TEETH_LOG" 2>/dev/null; then
         echo "SWEEP ОТКАЗ: образ прогона красен ещё до мутаций — реестр расходится с тем, что собрал этот прогон (лог $TEETH_LOG)" >&2
         tail -6 "$TEETH_LOG" >&2
         sum_line "# зубы реестра проверок: НЕ ИЗМЕРЕНЫ -- образ прогона красен до мутаций"
       else
         echo "SWEEP ОТКАЗ: прибор зубов НЕ МЕРИЛ: якорь мутации, длина замены или контроль (лог $TEETH_LOG)" >&2
         tail -6 "$TEETH_LOG" >&2
         sum_line "# зубы реестра проверок: НЕ ИЗМЕРЕНЫ -- прибор не может мерить"
       fi
       exit 2 ;;
    4) echo "SWEEP ОТКАЗ: таблица мутаций реестра не той длины, чем объявлено (лог $TEETH_LOG)" >&2
       tail -4 "$TEETH_LOG" >&2
       sum_line "# зубы реестра проверок: НЕ ИЗМЕРЕНЫ -- расхождение объявленного числа"
       exit 1 ;;
    6) # Круг 28, F-5: ребёнок объявляет и возвращает 6 (нет tools/checks-on-image.sh,
       # нет bash, сломанная машинерия замка -- круг 28, F-1). Раннер проверял
       # наличие файла ДО запуска, но неполный снимок кита падал в `*)` с текстом
       # «проверка прошла мутацию молча» -- чужой класс, чужой текст. Рука 6
       # стоит по образцу соседней руки 6 корпусного стенда выше.
       echo "SWEEP ОТКАЗ: машинерия прибора зубов сломана (нет bash/checks-on-image.sh, замок не открыть) -- зубы не мерили (лог $TEETH_LOG)" >&2
       tail -5 "$TEETH_LOG" >&2
       sum_line "# зубы реестра проверок: НЕ ИЗМЕРЕНЫ -- машинерия прибора сломана"
       exit 6 ;;
    *) echo "SWEEP ОТКАЗ: проверка прошла мутацию молча либо покраснела чужой дверью (код $__trc, лог $TEETH_LOG)" >&2
       tail -8 "$TEETH_LOG" >&2
       sum_line "# зубы реестра проверок: КРАСНЫЕ (код $__trc)"
       exit 1 ;;
    esac
  fi
  # Пропатченная копия зелёной версии удаляется, красной -- остаётся.
  #
  # Копий никто не читает после прогона, а весит каждая сотни мегабайт: восемь
  # версий за прогон -- и рабочий каталог занимает больше, чем свободно на
  # диске, на котором эти же сборки идут. У КРАСНОЙ версии копия -- главная
  # улика (что именно собралось), поэтому её сохраняем.
  if [[ "$note" != *КРАСНАЯ* && "$note" != *"НЕ ИЗМЕРЕНО"* ]]; then
    rm -f "$STATE/bin/$v.wave.bin"
  fi
  sum_line "$(printf '%s exit=%s ok=%s fail=%s tweakcc=%s ours=%s smoke=%s iface=%s bench=%s forms=%s floor=%s%s' \
    "$v" "$rc" "$ok" "$fail" "$tw" "$ours" "$smoke" "$iface" "$bench" "$forms" "$floor" "$note")"
  echo "SWEEP $v: exit=$rc ok=$ok fail=$fail tweakcc=$tw bench=$bench$note"
done
# Ни одна версия не собралась -- стадия зубов не исполнялась. Молчание
# здесь неотличимо от зелёного, поэтому отдельная строка и пометка в сводке.
if (( TEETH_DONE == 0 )); then
  echo "SWEEP зубы реестра: НЕ ИЗМЕРЕНЫ -- ни одна версия не собралась"
  sum_line "# зубы реестра проверок: НЕ ИЗМЕРЕНЫ -- ни одна версия не собралась"
fi
__drop_kit_when_idle

# Хвост говорит, что произошло, и код возврата это повторяет.
#
# Прежде последней строкой всегда было `SWEEP DONE`, а код возврата -- ноль,
# каким бы ни был исход версий: прогон, где семь версий из восьми не собрались,
# заканчивался тем же словом, что и полностью зелёный. Вердикт лежал в тексте
# сводки, но ничего снаружи нельзя было повесить на код возврата.
if (( ${#UNMEASURED[@]} || RED )); then
  line="SWEEP НЕПОЛНЫЙ (дерево $SWEPT_STATE): версий не измерено ${#UNMEASURED[@]}"
  (( ${#UNMEASURED[@]} )) && line="$line (${UNMEASURED[*]})"
  line="$line, вернувших ошибку $RED из ${#SRC[@]}"
  echo "$line"
  sum_line "# $line"
  # В UNMEASURED попадает ТОЛЬКО версия, чей прогон вернул 3 (замок конвейера
  # держал чужой прогон дольше бюджета), -- см. запись выше. Значит неполнота
  # без единой красной версии это «повторить позже», класс 3, а не отказ по
  # существу: прежде оба исхода уезжали кодом 1, и снаружи «кит красный» не
  # отличался от «машина была занята» (раунд 19, A-6).
  if (( RED == 0 )); then
    echo "  Красных версий нет: неполнота только из-за занятого замка -- повторить позже."
    exit 3
  fi
  exit 1
fi
# Зелёный вердикт пишется и В СВОДКУ. Прежде хвост `SWEEP DONE` уходил только
# в поток вывода, а красный -- ещё и в сводку: файл, который читают ПОСЛЕ
# прогона, у зелёного исхода не содержал вердикта вообще, и «прогон идёт»,
# «прогон отказал до сборки» и «всё зелено» читались в нём одинаково.
line="SWEEP DONE (дерево $SWEPT_STATE): все ${#SRC[@]} версий измерены, красных нет"
echo "$line"
sum_line "# $line"
__DONE=1   # штатный конец: см. «Часовой оборванного прогона» выше

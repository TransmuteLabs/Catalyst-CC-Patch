  exit 1; }
declare -a ALL=()
while IFS=$'\t' read -r label version pin; do
  [[ -n "${label:-}" ]] || continue
  ALL+=("$label:$version:$pin")
done <<< "$PARSED"
(( ${#ALL[@]} )) || { echo "SWEEP ОТКАЗ: список версий пуст: $LIST" >&2; exit 1; }

# Версии можно назвать аргументами: `sweep.sh 246 247`.
#
# 2026-08-27, решение юзера: пока идёт сходимость аудита, каждая волна правок
# меряется на 246 и 247 (~10 минут), а полный прогон с 233 делается ОДИН раз,
# когда сходимость достигнута. Прежний порядок гонял весь корпус после
# каждой волны, то есть тратил полчаса машины на вердикт о дереве, которое
# следующая волна всё равно переписывала.
#
# Неизвестное имя версии -- ОТКАЗ, а не тихий пропуск: опечатка в аргументе
# иначе дала бы пустой прогон с бодрым "SWEEP DONE" и нулём измерений.
declare -a SRC=()
if (( $# )); then
  for want in "$@"; do
    hit=""
    for entry in "${ALL[@]}"; do
      [[ "${entry%%:*}" == "$want" ]] && { SRC+=("$entry"); hit=1; break; }
    done
    [[ -n "$hit" ]] || { echo "SWEEP ОТКАЗ: версия '$want' не в списке (${ALL[*]%%:*})" >&2; exit 1; }
  done
  # Повтор в аргументах -- отказ. `sweep.sh 900 900` мерил один файл дважды и
  # печатал «все 2 версий измерены» (число -- счёт игрушечного корпуса,
  # docnum:other): тот же обман счёта, из-за которого разбор
  # списка отвергает одну версию под двумя метками.
  SET_NOTE="названы аргументами -- ${SRC[*]%%:*}"
  __dup=$(printf '%s\n' "${SRC[@]%%:*}" | sort | uniq -d | tr '\n' ' ')
  [[ -z "${__dup// /}" ]] || {
    echo "SWEEP ОТКАЗ: версия названа дважды: $__dup" >&2
    echo "  счёт «все N версий измерены» обещает N РАЗНЫХ версий" >&2
    exit 1; }
else
  # 2026-08-28, решение юзера: «дабы не тратить время на старое -- проверять
  # только на последних 5 версиях». Набор по умолчанию -- N САМЫХ НОВЫХ версий
  # списка по НОМЕРУ, а не последние N строк файла: строку в список дописывают
  # руками, и порядок в файле -- не гарантия. Полный корпус по-прежнему
  # достижим: назвать версии аргументами или SWEEP_LAST_N=0.
  # Вторая копия этого правила живёт в claude-patch-all.sh у
  # validated_nonnegative_integer; расхождение ловится сценарием стенда, а не
  # чтением. Общий файл здесь нельзя вводить: неполный список копирования кита
  # оставил бы один из двух исполняемых снимков без читателя.
  validated_nonnegative_integer() {
    local name="$1" value="$2" digits
    case "$value" in
      ''|*[!0-9]*)
        echo "SWEEP ОТКАЗ: $name='$value' -- не неотрицательное целое" >&2
        return 2
        ;;
    esac
    # Ведущие нули снимаются до сравнения и до арифметики: bash иначе читает
    # 08 как ошибочный восьмеричный литерал, а 0010 как восемь.
    digits="$value"
    while [[ "$digits" == 0* && "$digits" != "0" ]]; do digits="${digits#0}"; done
    if (( ${#digits} > 19 )) \
       || { [[ "${#digits}" == 19 ]] && [[ "$digits" > "9223372036854775807" ]]; }; then
      echo "SWEEP ОТКАЗ: $name='$value' -- больше 9223372036854775807" >&2
      return 2
    fi
    printf '%d\n' "$((10#$digits))"
  }
  # Отсутствие берёт умолчание, но ЯВНО заданная пустая строка остаётся
  # негодным значением и получает тот же код 2, что abc/-1/1.5: `${x:-d}`
  # смешало бы «не задано» и «задано пустым» до входа в валидатор.
  if [[ -z "${SWEEP_LAST_N+x}" ]]; then
    __n_raw="$SWEEP_LAST_N_DEFAULT"
  else
    __n_raw="$SWEEP_LAST_N"
  fi
  __n=$(validated_nonnegative_integer SWEEP_LAST_N "$__n_raw")
  __nrc=$?
  (( __nrc == 0 )) || exit "$__nrc"
  if (( __n == 0 )) || (( __n >= ${#ALL[@]} )); then
    SRC=("${ALL[@]}")
    SET_NOTE="ВЕСЬ корпус, ${#SRC[@]} версий (SWEEP_LAST_N=$__n)"
    echo "SWEEP набор: $SET_NOTE"
  else
    # Сортировка по НОМЕРУ версии (второе поле записи label:version:pin).
    declare -a __sorted=()
    while IFS= read -r __e; do [[ -n "$__e" ]] && __sorted+=("$__e"); done < <(
      printf '%s\n' "${ALL[@]}" | sort -t: -k2,2V)
    SRC=("${__sorted[@]: -__n}")
    SET_NOTE="последние $__n версий корпуса -- ${SRC[*]%%:*} (весь корпус: SWEEP_LAST_N=0 либо версии аргументами)"
    echo "SWEEP набор: $SET_NOTE"
  fi
fi
# Пустой набор -- самостоятельный отказ независимо от причины, которая его
# породила. Иначе хвост печатает «все 0 версий измерены» (docnum:example -- это
# цитата прежней строки хвоста, а не счёт кита) и превращает отсутствие
# измерения в зелёный вердикт.
if (( ${#SRC[@]} == 0 )); then
  echo "SWEEP ОТКАЗ: набор версий пуст -- мерить нечего" >&2
  exit 5
fi
# Отсутствующий образ -- ОТКАЗ, и до первой сборки.
#
# Прежде цикл печатал «нет исходника», записывал строку в сводку и продолжал:
# прогон на неполном корпусе заканчивался бодрым SWEEP DONE и набором зелёных
# строк, по которому нельзя отличить «померили всё» от «померили что нашлось».
# Именно так пропажа корпуса едва не прошла незамеченной. Проверка снята с
# цикла и вынесена вперёд: неполный корпус не тратит десять минут машины и не
# оставляет сводки, которую можно прочесть как вердикт.
# Путь образа выводится из версии одним местом: имя файла корпуса -- часть
# формата, а не догадка каждого потребителя.
. "$SWEEP_KIT/tools/corpus-file-name.sh"
src_of() { printf '%s/%s' "$CORPUS" "$(corpus_file_name "$1")"; }
ver_of() { local rest="${1#*:}"; printf '%s' "${rest%%:*}"; }
pin_of() { printf '%s' "${1##*:}"; }
declare -a MISSING=()
for entry in "${SRC[@]}"; do
  [[ -f "$(src_of "$(ver_of "$entry")")" ]] \
    || MISSING+=("${entry%%:*} ($(src_of "$(ver_of "$entry")"))")
done
if (( ${#MISSING[@]} )); then
  echo "SWEEP ОТКАЗ: нет пристинных образов: ${MISSING[*]}" >&2
  echo "  наполнить корпус: bash tools/fetch-corpus.sh" >&2
  exit 1
fi

# Корпус сверяется с пином ПЕРЕД прогоном.
#
# Наличие файла ничего не говорит о его содержимом: усечённая закачка,
# пропатченный по ошибке образ или подменённый файл дают измерение, по которому
# нельзя отличить «померили сток» от «померили патч поверх патча». Ровно этот
# класс уже приводил к зелёной сводке поверх загрязнённого артефакта (шапка
# выше). Пины -- третье поле corpus-versions.txt.
# Инструмент хеша выбирается ДО цикла: `exit 1` внутри функции, которую зовут
# только как `got=$(sha256_of ...)`, убивает подшелл, а не прогон -- отказ
# случался потом и по другой причине (пустой хеш не совпал с пином).
if command -v shasum >/dev/null 2>&1; then HASH=(shasum -a 256)
elif command -v sha256sum >/dev/null 2>&1; then HASH=(sha256sum)
else echo "SWEEP ОТКАЗ: нет ни shasum, ни sha256sum -- пин корпуса не проверить" >&2; exit 1
fi
# Пустой результат хеширования -- НЕ расхождение пина: файл без права чтения
# давал «на диске » и объявлялся подменённым, то есть причина отказа называлась
# неверно, а искать шли не там.
sha256_of() {
  local out
  out=$("${HASH[@]}" "$1" 2>/dev/null | awk '{print $1}')
  [[ -n "$out" ]] || return 1
  printf '%s' "$out"
}
declare -a TAINTED=()
for entry in "${SRC[@]}"; do
  v="${entry%%:*}"; src=$(src_of "$(ver_of "$entry")"); want=$(pin_of "$entry")
  if [[ "$want" == "-" ]]; then
    TAINTED+=("$v (пин не записан)"); continue
  fi
  if ! got=$(sha256_of "$src"); then
    TAINTED+=("$v (не прочитать $src)"); continue
  fi
  [[ "$got" == "$want" ]] || TAINTED+=("$v (пин $want, на диске $got)")
done
if (( ${#TAINTED[@]} )); then
  echo "SWEEP ОТКАЗ: корпус не сходится с пином: ${TAINTED[*]}" >&2
  exit 1
fi
echo "SWEEP версии: $(printf '%s ' "${SRC[@]%%:*}")"


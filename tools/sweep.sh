#!/usr/bin/env bash
# Version sweep: every pristine image through the whole pipeline.
# One line per version at the end; the full log per version stays on disk.
#
# 2026-08-27. Three guards were added after a sweep produced a green summary
# over a contaminated artifact. The previous sweep had been killed mid-run; its
# `node ... --apply` child survived the kill (killing a parent does not kill its
# descendants), kept the inherited log fd, and went on patching the SAME image
# path the restarted sweep was using. sweep-233.log ended up holding two
# tweakcc applies -- the second one AFTER our verification had already declared
# the image good -- with a 603-byte NUL hole between the interleaved streams.
#
#   * `grep -c` on a log with a NUL byte prints NOTHING and exits 1, so the
#     counts came out as EMPTY strings and the summary would have read
#     `ok= fail=`. Every count here is now `grep -a -c` and is asserted numeric.
#   * A log with a NUL byte is not evidence of anything: it is two streams.
#     Said on the summary line.
#   * Exactly one tweakcc apply and one of our applies per run. Two of either
#     means somebody else was writing to the same image.
#   * The run puts itself in its own process group, so a TERM to the group
#     takes the descendants with it. The door is `tools/sweep.sh --stop`:
#     it reads sweep.pgid, requires the group to be alive AND the recorded
#     start time of the group leader to still match (pgids are reused), and
#     only then signals. A stale file never aims the TERM at somebody
#     else's run; on any mismatch the door refuses having sent nothing.
#
# Последняя строка прогона -- ОДНА из двух: `SWEEP DONE ...` (все версии
# измерены, красных нет) или `SWEEP НЕПОЛНЫЙ ...` с ненулевым кодом возврата.
# Кто ждёт конца снаружи, должен искать обе: раньше `SWEEP DONE` печаталось
# всегда, чем бы прогон ни кончился.
#
# Коды выхода (подмножество общей таблицы кита -- шапка claude-patch-all.sh):
#   0  все названные версии измерены, красных нет
#   1  прогон отказал по существу (красная версия, отказ предполёта, битый корпус)
#   2  свип НЕ МЕРИЛ: предполётный прибор не смог мерить (сломан контракт его
#      вызова, переехала преамбула замка, пропал якорь вырезки) -- чинится не
#      тем, чем красный прогон
#   3  измерить сейчас нельзя, повтор поможет: замок свипа держит другой живой
#      свип; предполётный прибор занят; версия не измерена, потому что замок
#      конвейера держал чужой прогон дольше бюджета (и красных версий нет)
#   4  не возвращается: расхождение с пином версии уезжает красной строкой (1)
#   5  не возвращается: пропуск зонда «нечего мерить» в код свипа не входит
#   6  машинерия замка сломана (perl flock не работает) -- повтор не поможет
#
# Смерть по сигналу отдаётся как 128+N (130 INT, 143 TERM -- расщеплённые
# трапы ниже) и вердиктом кита НЕ является: POSIX сообщает сигнал, а эта
# таблица -- ответы свипа. Объявлено, потому что правило двустороннее:
# достижимый код обязан быть объявлен (круг 28, F-8).
#
# Достижимость 130 названа отдельно, потому что проверяется она не тем
# способом, каким её пробуют первым делом (замерено, круг 25, запрос F-6).
# 130 приходит, когда INT доставлен ГРУППЕ процессов -- так делает терминал
# по Ctrl-C. А `kill -INT <pid скрипта>` при живом foreground-ребёнке bash
# отбрасывает: ребёнок доживает своё, трап INT НЕ исполняется, прогон
# доходит до конца и отдаёт свой обычный код. Усечения при этом нет --
# отработало всё, поэтому такой код честен; но читатель, проверивший 130
# одиночным kill, решит, что трап сломан, и это ложный вывод.
#
# Ручки: SWEEP_STATE_DIR (корень рабочих путей), SWEEP_LOCK_BUDGET (сколько
# ждать замок конвейера, с), SWEEP_SKIP_BUILD_PROBE, SWEEP_SKIP_CHECKS_TEETH и SWEEP_SKIP_TOOLS_BENCH
# (выключают предполётные приборы -- каждый пропуск объявляется и в потоке, и в
# сводке), SWEEP_KIT_DRAIN (сколько секунд ждать процессы, поднятые ИЗ снимка
# кита, прежде чем его снести; по умолчанию 60 -- при оставшихся жильцах
# снимок сохраняется и называется), SWEEP_LAST_N (сколько САМЫХ НОВЫХ версий
# меряет прогон без аргументов, по умолчанию 5; 0 -- весь корпус),
# CORPUS_DIR и CORPUS_LIST (ЧТО меряется: дом образов и список версий
# с пинами -- не-дефолтное значение объявляется там же, потому что прогон по
# игрушечному корпусу иначе неотличим в сводке от боевого).
# Внутренние, руками не ставятся: SWEEP_LEADER, SWEEP_SELF, SWEEP_KIT.
set -u
# Все рабочие пути прогона -- под одним корнем, и корень переопределяем.
#
# Замок свипа, сводка, логи версий и копии образов лежали по фиксированным
# путям в /tmp/cc-matrix. Из-за этого стенд корпусных инструментов бился о
# ЖИВОЙ замок настоящего прогона и не мог проверить ни одной двери, пока идёт
# сборка. Одна ручка вместо трёх: боевое значение -- прежнее, стенд подставляет
# свой каталог и никому не мешает.
STATE="${SWEEP_STATE_DIR:-/tmp/cc-matrix}"
mkdir -p "$STATE/log" "$STATE/bin"

# Дверь остановки прогона -- сверкой, а не сигналом по записи из шапки.
# Номера групп переиспользуются: протухшая запись иначе целилась бы в ЧУЖОЙ
# прогон. Сигнал идёт только при живой группе И совпавшем времени старта её
# лидера; любое расхождение -- отказ кодом 1 без единого сигнала.
if [[ "${1:-}" == "--stop" ]]; then
  __rec="$(cat "$STATE/sweep.pgid" 2>/dev/null || true)"
  if [[ -z "$__rec" ]]; then
    echo "SWEEP --stop: нет записи прогона ($STATE/sweep.pgid) -- останавливать нечего" >&2
    exit 1
  fi
  if [[ "$__rec" != *$'\t'* ]]; then
    echo "SWEEP --stop: запись без метки времени старта -- не сигналить: $__rec" >&2
    exit 1
  fi
  __pgid="${__rec%%$'\t'*}"
  __start="${__rec#*$'\t'}"
  case "$__pgid" in ''|*[!0-9]*)
    echo "SWEEP --stop: запись не несёт номер группы: $__rec" >&2; exit 1 ;; esac
  if ! kill -0 -- -"$__pgid" 2>/dev/null; then
    echo "SWEEP --stop: группа $__pgid мертва -- останавливать нечего" >&2
    exit 1
  fi
  __now="$(LC_ALL=C ps -o lstart= -p "$__pgid" 2>/dev/null)"
  # Два случая, которые прежде склеивал один диагноз «переиспользован»:
  # ps ДАЛ метку и она не совпала -- номер действительно переиспользован; ps
  # пуст -- лидер группы мёртв, а группа жива (осиротевшие дети), и это не
  # переиспользование. Код возврата в обоих случаях 1, сигнал не уходит
  # (волна 26).
  if [[ -z "$__now" ]]; then
    echo "SWEEP --stop: лидер группы $__pgid мёртв, группа жива -- дверью не остановить" >&2
    echo "  нужен ручной сигнал по группе: kill -TERM -- -$__pgid" >&2
    exit 1
  fi
  if [[ "$__now" != "$__start" ]]; then
    echo "SWEEP --stop: номер группы $__pgid переиспользован, это не наш прогон" >&2
    echo "  (записан старт лидера: $__start; сейчас: $__now)" >&2
    exit 1
  fi
  kill -TERM -- -"$__pgid" || { echo "SWEEP --stop: не послать TERM группе $__pgid" >&2; exit 1; }
  echo "SWEEP --stop: TERM послан группе $__pgid"
  exit 0
fi

# Часовой оборванного прогона: bash 3.2 отдаёт код 0, когда скрипт с
# EXIT-трапом умирает на фатальной ошибке ПОДСТАНОВКИ (unbound variable под
# `set -u`, `${x:?}`, bad substitution) -- провал невидим вызывающему
# (измерено 2026-08-28). У свипа `set -u` без `set -e`, то есть это ЕГО класс:
# опечатка в имени переменной на ветке отказа печатала бы ошибку и отдавала
# ноль. Штатный конец объявляет себя (__DONE=1), трап без объявления краснит.
__DONE=0
__GUARD_KIT=0
# Снос снимка кита -- ОДНА процедура на оба выхода: трап и штатный хвост.
#
# `kill -TERM -<pgid>` (документированная остановка) приходит и свипу, и
# конвейеру, поднятому ИЗ СНИМКА. Свип успевал дойти до уборки, пока конвейер
# ещё сворачивался: bash читает тело скрипта по СМЕЩЕНИЮ и дочитывает его на
# ходу, а вспомогательные python/node запускаются из того же каталога -- снос
# рвал их в произвольном месте (круг 21, F-9). Ждём ограниченно, а если
# жильцы остались -- НЕ сносим и говорим об этом: осиротевший каталог дешевле
# порванного конвейера, и следующий прогон его назовёт.
#
# Почему процедура, а не код внутри трапа: первая редакция ждала жильцов
# только на пути отказа, а штатный хвост успешного прогона сносил снимок
# безусловным `rm -rf "$HERE"` -- гарантия держалась ровно на половине выходов
# (поймано сценарием 84 стенда корпусных инструментов).
#
# Снимок процессов снимается ДО awk: аргументы самого awk содержат путь
# снимка (`-v here=...`), и он засчитал бы себя жильцом.
__drop_kit_when_idle() {  # [путь, по умолчанию $HERE] [бюджет, по умолчанию SWEEP_KIT_DRAIN]
  local __path="${1:-${HERE:-}}" __wait_left="${2:-${SWEEP_KIT_DRAIN:-60}}" __snap_users __users
  [[ -n "$__path" ]] || return 0
  # Флаг принадлежит только СВОЕМУ снимку. Прополка чужого обломка проходит
  # тем же безопасным примитивом, но не имеет права снимать гвард текущего:
  # сигнал после такой прополки иначе оставил бы $HERE без штатной уборки.
  if [[ "$__path" == "${HERE:-}" ]]; then
    # Флаг снимается ДО цикла ожидания, а не после: дренаж -- единственная фаза
    # завершения, способная висеть до бюджета, и повторный вход в гвард (сигнал
    # посреди ожидания) иначе стартовал бы дренаж СО СВЕЖИМ бюджетом. Снятый
    # заранее флаг держит суммарное ожидание в пределах одного бюджета.
    __GUARD_KIT=0
  fi
  # Проверка ВСЕГДА хотя бы одна: с нулевым бюджетом ожидания цикл `while ((
  # __wait_left > 0 ))` не исполнялся ни разу, `__users` оставался пустым, и
  # снимок сносился без единого взгляда на жильцов.
  while :; do
    __snap_users=$(ps -eo pid,args)
    __users=$(printf '%s\n' "$__snap_users" | awk -v here="$__path" -v me="$$" '
      $1 != me && index($0, here) { print $1 }' || true)
    [[ -z "$__users" ]] && break
    (( __wait_left > 0 )) || break
    sleep 1
    __wait_left=$(( __wait_left - 1 ))
  done
  if [[ -z "$__users" ]]; then
    rm -rf "$__path"
    return 0
  fi
  echo "SWEEP: снимок кита НЕ убран -- из него ещё исполняются процессы (pid: $__users)" >&2
  echo "  каталог: $__path" >&2
  return 0
}
__exit_guard() {
  __rc=$?
  rm -f "${SWEEP_SELF:-}"
  # Снимок кита сносится ТОЛЬКО когда из него больше никто не исполняется --
  # тем же примитивом, что и на штатном хвосте (см. __drop_kit_when_idle).
  (( __GUARD_KIT )) && __drop_kit_when_idle
  # Номер группы -- инструмент остановки ЖИВОГО прогона. Файл переживал прогон,
  # а номера групп переиспользуются: следующий читатель слал бы TERM чужой
  # группе по нашей же инструкции (раунд 19, В-7). Убирает его ТОЛЬКО тот, кто
  # его записал: свип, отказавший на занятом замке, снёс бы номер ЖИВОГО
  # держателя -- ровно ту потерю, ради которой запись и переехала под замок.
  # Снимается ПОСЛЕ дренажа: дренаж -- единственная фаза завершения, которая
  # может висеть до бюджета, и проходить её уже без средства остановки -- та
  # же потеря, что и у флага уборки выше.
  [[ "${__PGID_OURS:-0}" == 1 && -n "${STATE:-}" ]] && rm -f "$STATE/sweep.pgid"
  if [[ "${__DONE:-0}" != 1 && "$__rc" == 0 ]]; then
    echo "SWEEP ОТКАЗ: прогон оборвался, не дойдя до конца (ошибка оболочки выше)" >&2
    exit 1
  fi
  exit "$__rc"
}
if [[ "${SWEEP_LEADER:-}" != "1" ]]; then
  # Кит запоминается ДО ре-экзека: дальше скрипт исполняется из своей копии в
  # /tmp, и dirname его пути указывал бы уже туда.
  SWEEP_KIT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
  # Круг 24: этот корень ниже копируется ЦЕЛИКОМ (`cp -R "$SRC_KIT"/. "$HERE"/`),
  # и из копии ЗАПУСКАЕТСЯ конвейер. Ошибка вывода корня здесь дороже, чем у
  # стендов: на соседнем инструменте замерено, как KIT стал корнем файловой
  # системы и 3.8 ГБ уехали в tmp до ручной остановки, а тут из скопированного
  # каталога ещё и исполнился бы чужой claude-patch-all.sh. Подпись кита --
  # три его файла; проверка стоит ДО ре-экзека, то есть до первой копии и до
  # первого процесса. Код 2 «свип НЕ МЕРИЛ» -- это отказ прибора, не вердикт.
  for __sig in claude-patch-all.sh tools/sweep.sh tools/corpus-versions.txt; do
    if [[ ! -f "$SWEEP_KIT/$__sig" ]]; then
      echo "SWEEP НЕ МЕРИЛ: корень «${SWEEP_KIT}» не кит -- нет ${__sig}." >&2
      echo "  Свип выводит кит из пути своего файла, копирует его целиком и" >&2
      echo "  запускает конвейер ИЗ КОПИИ; звать только как tools/sweep.sh" >&2
      echo "  внутри кита." >&2
      exit 2
    fi
  done
  unset __sig
  export SWEEP_KIT SWEEP_LEADER=1
  # Скрипт переехал из /tmp внутрь кита, а кит правится, пока прогон идёт (в
  # этом и был смысл снимка кита ниже). bash читает тело исполняемого файла по
  # СМЕЩЕНИЮ и дочитывает его на ходу, поэтому правка файла на диске рвёт
  # текущий прогон в произвольном месте. Лидер исполняет СОБСТВЕННУЮ копию,
  # так что файл в репозитории свободен всё время прогона -- ровно та свобода,
  # ради которой снимался кит.
  # Без perl нет ни своей сессии, ни setsid. Прежде `exec perl` просто не
  # находил перехватчика, оболочка выходила из `if` и работала лидером в чужой
  # группе процессов -- ровно то, что шапка объявляет невозможным, и молча.
  command -v perl >/dev/null 2>&1 || {
    echo "SWEEP ОТКАЗ: нет perl -- прогон не отделить в свою сессию" >&2; exit 1; }
  SWEEP_SELF=$(mktemp "$STATE/sweep.self.XXXXXX") || {
    echo "SWEEP ОТКАЗ: не создать копию себя" >&2; exit 1; }
  # Уборка ставится ДО первой записи в копию: неудачное копирование выходило по
  # `exit 1` раньше, чем появлялся trap ниже, и оставляло пустой файл в /tmp.
  # Сигнальные трапы переводят сигнал в КОД (130/143), а общий выход -- в
  # EXIT-трап: точечный TERM от оператора иначе приходился на последнюю
  # УДАВШУЮСЯ команду, и часовой объявлял остановку «ошибкой оболочки».
  trap '__exit_guard' EXIT
  trap 'exit 130' INT
  trap 'exit 143' TERM
  cat "$0" > "$SWEEP_SELF" || { echo "SWEEP ОТКАЗ: не скопировать себя" >&2; exit 1; }
  export SWEEP_SELF
  exec perl -e 'use POSIX ();
    my $sid = POSIX::setsid();
    if (!defined($sid) || $sid < 0) {
      my $child = fork();
      defined($child) or do { print STDERR "SWEEP ОТКАЗ: fork отказал ($!) -- прогон не отделить в свою сессию\n"; exit 1 };
      # Убитый сигналом ребёнок даёт сырой статус N, а чтение `>> 8` превращало
      # его в ноль: обёртка рапортовала успех об убитом прогоне (волна 26).
      # Смерть от сигнала поднимается в код 128+N -- та же форма, что даёт bash.
      if ($child) { waitpid($child, 0); exit(($? & 127) ? 128 + ($? & 127) : ($? >> 8)) }
      $sid = POSIX::setsid();
      (!defined($sid) || $sid < 0) and do { print STDERR "SWEEP ОТКАЗ: setsid в ребёнке отказал ($!) -- прогон не отделить в свою сессию\n"; exit 1 };
    }
    exec @ARGV or die $!' bash "$SWEEP_SELF" "$@"
fi
# Копия себя убирается на любом выходе ЧЕРЕЗ ТРАП, а не только на успешном:
# дверей отказа у этого скрипта после сюда девять, и на каждой явный rm в
# хвосте не исполняется -- /tmp копил бы по копии на отказ.
#
# «Любой выход» -- это выход, который трап видит. SIGKILL и падение машины его
# не исполняют, поэтому обломки всё-таки остаются; их убирает прополка под
# замком ниже, и предел объявлен здесь, а не подразумевается.
trap '__exit_guard' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

# Собственный замок свипа.
#
# Страж выше ловит ЧУЖОЙ уже идущий claude-patch-all.sh, но не свип-ровесника,
# который сам ещё не дошёл до первой сборки: оба проходят стража, а дальше
# делят `sweep-summary.txt` (второй стартовавший обрезает накопленные строки
# первого), один и тот же `bin/<версия>.wave.bin` и один и тот же лог версии.
# Сборки при этом сериализует замок конвейера -- теряется не сборка, а ЗАПИСЬ
# вердикта, то есть ровно то, ради чего свип и запускают.
#
# Дескриптор закрывается у детей (`8>&-` на вызове конвейера): переживший нас
# ребёнок иначе продолжал бы держать замок свипа -- тот самый класс, из-за
# которого прогон корпуса уже терял версии.
exec 8>"$STATE/sweep.lock"
# Код возврата снимается ОТДЕЛЬНОЙ строкой, без `if !`.
#
# После `if ! cmd; then` переменная `$?` внутри ветки равна нулю: её значение --
# результат ОТРИЦАНИЯ, а не самой команды. Первая редакция читала там код perl и
# всегда печатала «не взять замок свипа (perl rc=0)» вместо «другой свип уже
# идёт» -- то есть занятый замок объявлялся поломкой инструмента.
perl -e 'use Fcntl ":flock"; open(my $fh, ">&=8") or exit 2;
         exit(flock($fh, LOCK_EX|LOCK_NB) ? 0 : 1);'
__rc=$?
if (( __rc != 0 )); then
  if (( __rc == 1 )); then
    echo "SWEEP ОТКАЗ: другой свип уже идёт (замок $STATE/sweep.lock)." >&2
    echo "  кто именно: lsof $STATE/sweep.lock" >&2
    exit 3
  fi
  echo "SWEEP ОТКАЗ: не взять замок свипа -- машинерия замка сломана (perl rc=$__rc)" >&2
  echo "  Повтор не поможет: чинить окружение." >&2
  exit 6
fi

# Единственный писатель сводки. И обнуление, и дописывание идут через него.
#
# Писателей было ДВА -- ранний блок с перенаправлением и `sum_line`, -- и
# проверок было тоже две. Для работы этого хватало, для зубов нет: мутация,
# снявшая проверку у одного, гасилась отказом другого, и стенд не мог показать
# ни одной поломки гарантии. Хуже того, ВТОРОЕ обнуление (`: > "$SUMMARY"`
# перед циклом версий) проверки не имело вовсе -- ровно тот класс, против
# которого заведена сама гарантия (найдено самопроверкой стенда корпуса,
# круг 21, волна 24).
#
# ЗАПИСЬ ПРОВЕРЯЕТСЯ. Гарантия «первая же строка нового прогона делает файл
# нечитаемым как вердикт» держится на ней, а `set -e` здесь не включён: молча
# провалившаяся запись (файл только для чтения, нет места, каталог чужой)
# оставляла на диске ЗЕЛЁНЫЙ вердикт прошлого прогона.
#
# ФОРМА -- НЕ УКРАШЕНИЕ. `if ! { ...; } > файл; then` в bash 3.2 НЕ видит
# провала перенаправления: оболочка печатает «Permission denied», а условие
# оказывается ложным, и прогон едет дальше (измерено 2026-08-28). Поэтому
# перенаправление стоит отдельной командой, а её код возврата -- в $rc.
SUMMARY="$STATE/log/sweep-summary.txt"
sum_write() {   # $1 = reset|add, далее строки; 1 -- запись не удалась
  local mode="$1" rc=0
  shift
  if [[ "$mode" == reset ]]; then
    : > "$SUMMARY" || rc=1
  fi
  if (( rc == 0 )) && (( $# )); then
    printf '%s\n' "$@" >> "$SUMMARY" || rc=1
  fi
  return $rc
}

sum_reset() {   # обнулить сводку и, если переданы, положить строки заголовка
  sum_write reset "$@" && return 0
  echo "SWEEP ОТКАЗ: не обесценить сводку $SUMMARY --" >&2
  echo "  на диске остался бы вердикт ПРОШЛОГО прогона." >&2
  exit 1
}

# Имя не `note`: в цикле версий уже живёт ПЕРЕМЕННАЯ с этим именем, и
# одноимённость сбивала бы читателя, хотя bash их и различает.
sum_line() {    # дописать ОДНУ строку
  sum_write add "$*" && return 0
  echo "SWEEP ОТКАЗ: не дописать строку в сводку $SUMMARY: «$*»" >&2
  echo "  Сводку читают вместо логов; молча продолжать нельзя." >&2
  exit 1
}

# Сводка обесценивается СРАЗУ, а не после всех дверей отказа.
#
# Обрезалась она только перед циклом версий, то есть после четырнадцати
# `SWEEP ОТКАЗ`. Прогон, отказавший на любой из них, оставлял на диске сводку
# ПРОШЛОГО прогона -- с зелёными строками и прежним вердиктом, -- и читатель
# файла видел успех, которого в этом прогоне не было. Первая же строка нового
# прогона делает файл нечитаемым как вердикт; успешный проход перезапишет её.
#
# Раньше замка писать нельзя: там ещё возможен ЖИВОЙ свип-ровесник, и запись
# затёрла бы копящиеся строки его прогона -- ровно то, из-за чего замок и
# заведён. Поэтому три двери ДО замка (нет perl, не скопировать себя) сводку
# не трогают: прогон в них не начался, но и старый файл остаётся -- предел
# объявлен здесь, а не спрятан.
#
sum_reset "# ПРОГОН НАЧАТ $(date '+%F %T'), вердикта ещё нет." \
          "# Эта строка остаётся, если прогон отказал до первой сборки:" \
          "# причина -- в потоке ошибок прогона, а не здесь."

# Обломки прошлых прогонов убираются ЗДЕСЬ, под замком.
#
# Снимок кита (`kit.XXXXXX`), копия себя (`sweep.self.XXXXXX`) и номер группы
# (`sweep.pgid`) убираются трапом на любом выходе -- но трап не исполняется на
# SIGKILL и на падении машины, а снимок кита весит мегабайты, и протухший номер
# группы опасен не байтами, а НАПРАВЛЕННОЙ остановкой: дверь `--stop` обязана
# не встречать его на диске. Под замком соперника нет, и всё, что старше суток,
# принадлежит прогону, которого уже нет: живой прогон держит замок, а не мы.
# Своё (текущее) не трогаем по имени -- и своей записи ещё нет: она делается
# НИЖЕ, после прополки, чтобы прополка не смотрела на собственный файл.
# Метка в будущем -- не признак живого писателя, а испорченная метка (шаг
# часов назад, копия с машины вперёд): такой обломок считается протухшим
# наравне со старым. Порог +60 c общий с judge/compact.py.
__stale_future() {   # путь; 0 -- метка в будущем
  local m
  m=$(stat -f %m "$1" 2>/dev/null || stat -c %Y "$1" 2>/dev/null) || return 1
  [[ "$m" =~ ^[0-9]+$ ]] || return 1
  (( m > $(date +%s) + 60 ))
}
for __stale in "$STATE"/kit.?????? "$STATE"/sweep.self.?????? "$STATE"/sweep.pgid; do
  [[ -e "$__stale" ]] || continue
  [[ "$__stale" == "${SWEEP_SELF:-}" ]] && continue
  if [[ -z "$(find "$__stale" -maxdepth 0 -mtime +0 2>/dev/null)" ]] \
     && ! __stale_future "$__stale"; then continue; fi
  # Каталоги kit.* и sweep.self.* исполняют shell/python/node прямо из
  # себя, поэтому даже протухший по времени обломок удаляется только после
  # проверки жильцов. sweep.pgid -- файл данных, из него ничего не исполняется:
  # ему ожидание не даёт гарантии и он остаётся прямым rm -f.
  case "$__stale" in
    */sweep.pgid)
      rm -f "$__stale" && echo "SWEEP убрал обломок прошлого прогона: $__stale" ;;
    *)
      __drop_kit_when_idle "$__stale" 0
      [[ -e "$__stale" ]] || echo "SWEEP убрал обломок прошлого прогона: $__stale" ;;
  esac
done

# Идентификатор группы пишется ПОСЛЕ замка и ПОСЛЕ прополки.
#
# Прежде он писался до захвата: свип-ровесник, который через секунду отказал бы
# на занятом замке, успевал переписать `sweep.pgid` своим номером, и файл,
# существующий ради одной операции -- остановки, -- направлял её на ЧУЖУЮ,
# уже мёртвую группу. Теперь номер в файле принадлежит тому, кто держит замок,
# а прополка выше уже сняла протухшую запись прежнего прогона. Запись несёт
# pgid И время старта лидера группы: переиспользованный номер иначе неотличим
# от живого прогона, и дверь `--stop` целилась бы в чужую группу (шапка).
# Форма метки одна на оба конца двери: LC_ALL=C ps -o lstart= -p <pid>.
#
# Метка снимается в переменную и проверяется на непустоту (волна 26): отказавший
# ps клал бы в файл «PID\t», дверь --stop прочла бы запись без метки и отказала
# бы ВЕСЬ прогон с диагнозом «номер группы переиспользован» -- неверным. Пустая
# метка -- не повод валить прогон: файл не создаётся, __PGID_OURS остаётся нулём
# (трап его не убирает -- его и нет), а поток объявляет недоступность двери.
__lstart="$(LC_ALL=C ps -o lstart= -p "$$" 2>/dev/null)"
if [[ -n "$__lstart" ]]; then
  if printf '%s\t%s\n' "$$" "$__lstart" > "$STATE/sweep.pgid"; then
    __PGID_OURS=1
  else
    echo "SWEEP ОТКАЗ: не записать $STATE/sweep.pgid -- прогон было бы нечем остановить" >&2
    exit 1
  fi
else
  __PGID_OURS=0
  # Своей записи не будет -- значит и ЧУЖОЙ тут быть не должно. Прополка выше
  # щадит запись моложе суток, а замок гарантирует, что живой свип здесь один:
  # уцелевшая запись принадлежит УПАВШЕМУ прогону, и дверь --stop ветвилась бы
  # по ней, объявляя «группа мертва» или «номер переиспользован», пока живой
  # прогон работает. Отсутствие записи -- честный ответ «останавливать нечем».
  rm -f "$STATE/sweep.pgid"
  echo "SWEEP NOTE: ps не дал метку старта лидера -- дверь --stop для этого прогона" >&2
  echo "  недоступна (записи с пустой меткой дверь не доверяет). Прогон продолжается." >&2
fi

# A previous run's helper still alive would race us on the same image paths.
# The snapshot is taken BEFORE awk starts, so awk cannot find its own command
# line -- which carries the very patterns it searches for. A `ps | awk '/pat/'`
# pipeline matches itself, and a guard that always finds a victim is no guard.
# In `ps -eo pid,args` the script path is NOT $2 -- $2 is the interpreter
# (`bash`), the path is $3. The first form of this guard tested $2 and therefore
# could never fire: verified with a positive control, a fake
# `bash <dir>/claude-patch-all.sh` that the guard walked straight past.
#
# Путь конвейера в аргументах ЕЩЁ НЕ ЗНАЧИТ, что конвейер идёт: путь может
# стоять аргументом ЧУЖОЙ программы (просмотрщик, редактор, гейт чисел
# `python3 <кит>/.docnum-gate.py <кит>/claude-patch-all.sh`), и страж
# объявлял живым прогоном и отказывал. Поэтому второе поле обязано быть
# ИНТЕРПРЕТАТОРОМ -- ^(/.*/)?(bash|sh)$ -- и только тогда третье поле
# читается как путь нашего скрипта: `bash <путь>` -- прогон,
# `tail -f <путь>` и `python3 gate.py <путь>` -- нет.
snap=$(ps -eo pid,args)
alive=$(printf '%s\n' "$snap" | awk '
  $2 ~ /^(\/.*\/)?(bash|sh)$/ && $3 ~ /claude-patch-all\.sh$/ { print $1 }
  /catalyst-tweakcc.*index\.mjs.*(--apply|adhoc-patch)/ { print $1 }' || true)
if [[ -n "$alive" ]]; then
  # Класс 3, а не 1. Чужой живой конвейер -- это «измерить СЕЙЧАС нельзя,
  # повтор поможет», ровно как занятый замок двумястами строками ниже, где тот
  # же случай получает 3 и бюджет ожидания. Код 1 объявлял бы отказ ПО
  # СУЩЕСТВУ -- то есть чинить кит, -- и расходился с таблицей кодов в шапке
  # этого же файла (круг 21, линза F, находка 2). И прогон чужой, а не
  # «предыдущий»: оператор вправе собирать в соседнем окне.
  echo "SWEEP ОТКАЗ: живы процессы чужого прогона конвейера: $alive" >&2
  echo "  Свипу нужен тот же замок: повторить, когда чужой прогон кончится." >&2
  exit 3
fi

# Дом корпуса пристинных образов.
#
# 2026-08-28. Корпус жил в ~/.local/share/claude/versions как <версия>.orig, и
# фаза «Cleaning up previous versions» самого конвейера его стёрла: она удаляет
# из этого каталога ВСЁ, кроме текущей версии и той, что исполняет живая сессия.
# То есть успешная установка новой версии уничтожала измерительную базу, на
# которой меряется следующая волна. Образы 233/240/243/245/246 так и пропали.
# У корпуса теперь свой каталог, куда очистка не заглядывает; наполняется он
# из реестра npm (tools/fetch-corpus.sh), а не копированием локальной
# установки: локальная копия может быть уже пропатченной.
# Дом корпуса и список версий переопределяемы -- этим пользуется стенд
# tools/corpus-tools-bench.sh: двери отказа надо уметь проверить на
